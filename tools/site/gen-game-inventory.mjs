#!/usr/bin/env node
// Generates docs/workflows/game-inventory.json: the single source of the public game count.
// A game is "live" only when its app folder exists AND the production build serves it
// (showcaseRoutes in marketing/scripts/build-showcase-routes.mjs).
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CHECK = process.argv.includes("--check");
const OUT = join(repoRoot, "docs", "workflows", "game-inventory.json");

const catalog = JSON.parse(readFileSync(join(repoRoot, "tools", "site", "games.catalog.json"), "utf8"));
const routesSource = readFileSync(join(repoRoot, "marketing", "scripts", "build-showcase-routes.mjs"), "utf8");

function arrayLiteral(name) {
  const match = routesSource.match(new RegExp(`const ${name} = \\[([\\s\\S]*?)\\];`));
  if (!match) throw new Error(`build-showcase-routes.mjs: array ${name} not found`);
  return [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

const served = new Set(arrayLiteral("showcaseRoutes"));
const retired = new Set(arrayLiteral("retiredPrototypeRoutes"));

function listImages(dir, rel) {
  const out = [];
  for (const entry of readdirSync(join(dir, rel), { withFileTypes: true })) {
    const next = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...listImages(dir, next));
    else if (/\.(jpe?g|png)$/i.test(entry.name)) out.push(next);
  }
  return out.sort();
}

function screensFor(evidenceFolder) {
  for (const sub of ["screens/final", "screens/2026-10-24"]) {
    const dir = join(repoRoot, "evidence", evidenceFolder, sub);
    if (!existsSync(dir)) continue;
    const files = listImages(dir, "");
    if (files.length === 0) continue;
    const cards = files.filter((f) => /card/i.test(f));
    const pick = cards.find((f) => /(2x|@2x)/i.test(f)) ?? cards[0] ?? null;
    return { set: sub.endsWith("final") ? "final" : "2026-10-24", dir: `evidence/${evidenceFolder}/${sub}`, card: pick, frameCount: files.length };
  }
  return null;
}

const games = catalog.games.map((entry) => {
  const appDir = join(repoRoot, "apps", entry.appFolder);
  const isServed = served.has(entry.appFolder);
  const status = existsSync(appDir) && isServed ? "live" : retired.has(entry.appFolder) ? "retired" : "hidden";
  const screens = screensFor(entry.evidenceFolder);
  return {
    slug: entry.previewSlug,
    appFolder: entry.appFolder,
    title: entry.title,
    url: entry.url,
    kind: "game",
    genre: entry.genre,
    status,
    verification: entry.verification,
    evidenceFolder: `evidence/${entry.evidenceFolder}`,
    screens: screens ? { set: screens.set, dir: screens.dir, card: screens.card, frameCount: screens.frameCount } : null
  };
});

const live = games.filter((g) => g.status === "live");
const genreCounts = Object.fromEntries(Object.keys(catalog.genres).map((k) => [k, live.filter((g) => g.genre === k).length]));

const inventory = {
  schema: "aura3d-game-inventory/1",
  note: "Generated by tools/site/gen-game-inventory.mjs. Do not edit. liveGameCount is the only count the site may state.",
  liveGameCount: live.length,
  genres: catalog.genres,
  genreCounts,
  games
};

const next = `${JSON.stringify(inventory, null, 2)}\n`;
if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  // The Vercel build excludes evidence/, so screenshot fields cannot be recomputed there: compare everything else.
  const withoutScreens = (text) => JSON.stringify(JSON.parse(text, (key, value) => (key === "screens" ? undefined : value)));
  // An empty evidence/ directory can exist in the Vercel build, so test for a game evidence folder, not the top-level dir.
  const evidencePresent = catalog.games.some((g) => existsSync(join(repoRoot, "evidence", g.evidenceFolder)));
  const same = evidencePresent ? current === next : current !== "" && withoutScreens(current) === withoutScreens(next);
  if (!same) {
    console.error("game-inventory.json is stale: run `node tools/site/gen-game-inventory.mjs`");
    process.exit(1);
  }
  console.log(`game-inventory --check: OK (${inventory.liveGameCount} live games)`);
} else {
  writeFileSync(OUT, next, "utf8");
  console.log(`wrote ${OUT}: ${inventory.liveGameCount} live games`);
  console.log(JSON.stringify(genreCounts));
}
