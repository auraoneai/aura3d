#!/usr/bin/env node
// Mechanical UMD -> ES module conversion of the hand-written tennis simulation scripts. The converted function bodies are
// byte-for-byte the originals (behaviour must not drift); typed, split modules are extracted from them afterwards and
// guarded by differential tests against the original scripts. Usage: node tools/aura-slam/port-sim.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const SRC = "apps/showcase-top-tennis/public/toptennis/";
const OUT = "examples/aura-slam/sim/";
const UMD = /\}\)\(typeof window==='undefined'\?globalThis:window,function\(([^)]*)\)\{/;

function convert(file, exportName, outFile, opts = {}) {
  const src = readFileSync(SRC + file, "utf8");
  const m = src.match(UMD);
  if (!m) throw new Error(`${file}: UMD wrapper not recognised`);
  const params = m[1].split(",").map((p) => p.trim()).filter(Boolean);
  const body = src.slice(m.index + m[0].length, src.lastIndexOf("});"));
  const sha = createHash("sha256").update(src).digest("hex").slice(0, 16);
  const head = `// Generated by tools/aura-slam/port-sim.mjs from public/toptennis/${file} (sha256 ${sha}...). Do not edit by hand:\n` +
    `// the body is the original, converted from a UMD factory to an ES module so behaviour stays identical.\n` +
    `// @ts-nocheck: dense legacy closure; the typed surface lives in the sibling modules and the differential tests.\n`;
  const sig = params.map((p) => `${p}: any`).join(", ");
  const tail = opts.instance ? `\nexport const ${exportName} = ${exportName}Factory();\n` : "";
  const name = opts.instance ? `${exportName}Factory` : exportName;
  writeFileSync(OUT + outFile, `${head}export function ${name}(${sig}): any {${body}}\n${tail}`);
  console.log(`wrote ${OUT}${outFile} (${body.length} chars from ${file})`);
}

convert("player-appearance.js", "appearance", "appearance.ts", { instance: true });
convert("player-roster.js", "roster", "roster.ts", { instance: true });
convert("match-engine.js", "engineModule", "engine.ts");
