// Extracts the live Aura Slam athlete-rig code from apps/showcase-top-tennis/src/main.ts and transpiles it to a
// self-contained JS factory so the native port can be differential-tested against the REAL original code.
//   node tools/aura-slam/extractOriginalRig.mjs          write examples/aura-slam/view/__generated__/originalRig.js
//   node tools/aura-slam/extractOriginalRig.mjs --check  exit 1 if the committed file is stale
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const MAIN_PATH = resolve(root, "apps/showcase-top-tennis/src/main.ts");
export const OUT_PATH = resolve(root, "examples/aura-slam/view/__generated__/originalRig.js");

function between(source, startMarker, endMarker) {
  const a = source.indexOf(startMarker);
  const b = source.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`marker not found: ${startMarker} .. ${endMarker}`);
  return source.slice(a, b);
}

export function extractOriginalRig(mainSource) {
  const consts = between(mainSource, "const COURT_X = 5.5;", "function clamp(");
  const helpers = between(mainSource, "function clamp(", "interface AthleteRigHandles");
  const rig = between(mainSource, "function updateAthleteRig(", "const TRAIL_COUNT");
  const body = `${consts}\n${helpers}\n${rig}`;
  const js = ts.transpileModule(body, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: false }
  }).outputText;
  const hash = createHash("sha256").update(body).digest("hex").slice(0, 16);
  return (
    `// GENERATED by tools/aura-slam/extractOriginalRig.mjs from apps/showcase-top-tennis/src/main.ts (source hash ${hash}).\n` +
    `// Do not edit. It exists only so tests can differential-test the native port against the real original code.\n` +
    `export function createOriginalRig({ game, material, window }) {\n${js}\nreturn { updateAthleteRig, COURT_X, COURT_Z, HIDDEN_SCALE };\n}\n`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = extractOriginalRig(readFileSync(MAIN_PATH, "utf8"));
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT_PATH, "utf8"); } catch { /* missing */ }
    if (current !== next) { console.error("originalRig.js is stale; run node tools/aura-slam/extractOriginalRig.mjs"); process.exit(1); }
    console.log("originalRig.js is up to date");
  } else {
    writeFileSync(OUT_PATH, next);
    console.log(`wrote ${OUT_PATH} (${next.length} bytes)`);
  }
}
