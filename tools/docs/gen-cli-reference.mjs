#!/usr/bin/env node
// Generates docs/api/cli-reference.md from the CLI's own catalog (`aura3d help --json`),
// so the reference cannot drift from what the CLI accepts.
//
// Usage (repo root):
//   node tools/docs/gen-cli-reference.mjs                 write docs/api/cli-reference.md
//   node tools/docs/gen-cli-reference.mjs --check         exit 1 when the file is stale
//   node tools/docs/gen-cli-reference.mjs --verify-docs a.md b.txt ...
//        exit 1 when a doc names an `aura3d <command>` the catalog lacks, or a flag that
//        command's usage does not list (global --help/--version/--json always allowed)
//   --from help.json   read a saved `aura3d help --json` instead of running the CLI from source
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "docs/api/cli-reference.md");

function loadCatalog(argv) {
  const fromAt = argv.indexOf("--from");
  if (fromAt >= 0) return JSON.parse(readFileSync(path.resolve(argv[fromAt + 1]), "utf8"));
  const tsx = path.join(ROOT, "node_modules/.bin/tsx");
  if (!existsSync(tsx)) throw new Error("node_modules/.bin/tsx is missing: run pnpm install, or pass --from <help.json>");
  const stdout = execFileSync(tsx, ["--tsconfig", "tsconfig.base.json", "packages/aura3d-cli/src/cli.ts", "help", "--json"], {
    cwd: ROOT,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
    maxBuffer: 32 * 1024 * 1024
  });
  const catalog = JSON.parse(stdout);
  if (catalog.schema !== "aura3d.cli-help/1") throw new Error(`unexpected help --json schema ${catalog.schema}`);
  return catalog;
}

/**
 * Flags the command itself accepts: those on synopsis lines (`aura3d <name> ...`, `[...]` continuations)
 * plus the leading flag of an option-definition line. Prose such as "then run aura3d assets add --name"
 * names another command's flag, so it is not counted (the raw `flags` array of help --json does count it).
 */
function ownFlags(command) {
  const flags = new Set();
  const top = command.name.split(" ")[0];
  for (const raw of command.usage.split("\n")) {
    const line = raw.trim();
    if (line.startsWith(`aura3d ${command.name}`) || line.startsWith("[") || (top === command.name && line.startsWith(`aura3d ${top}`))) {
      for (const segment of line.split(/\s\|\s(?=aura3d )/)) {
        if (!segment.startsWith("aura3d ") && !segment.startsWith("[")) continue;
        for (const m of segment.matchAll(/(?<![\w-])--[a-z0-9][a-z0-9-]*/gi)) flags.add(m[0]);
      }
    } else if (line.startsWith("--")) {
      const lead = /^(--[a-z0-9][a-z0-9-]*)((?:\|--[a-z0-9][a-z0-9-]*)*)/i.exec(line);
      if (lead) for (const f of lead[0].split("|")) flags.add(f);
    }
  }
  return [...flags].sort();
}

const GROUP_TITLES = {
  assets: "Assets",
  animation: "Animation",
  look: "Look-dev",
  migrate: "Migration",
  vfx: "VFX",
  perf: "Performance",
  core: "Core",
  environments: "Environments",
  evidence: "Evidence",
  sfx: "Audio",
  prd08: "Motion evidence"
};

function groupOf(name) {
  const top = name.split(" ")[0];
  return GROUP_TITLES[top] && name.includes(" ") ? top : top === "perf-report" ? "perf" : "project";
}

function escapeCell(text) {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function anchor(name) {
  return `aura3d-${name.replaceAll(" ", "-")}`;
}

function render(catalog) {
  const commands = catalog.commands;
  const groups = new Map();
  for (const command of commands) {
    const group = groupOf(command.name);
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(command);
  }
  const order = ["project", "assets", "animation", "look", "evidence", "migrate", "environments", "vfx", "perf", "core", "sfx", "prd08"];
  const groupNames = [...groups.keys()].sort((a, b) => (order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99));
  const title = (group) => (group === "project" ? "Project, agent and deploy" : GROUP_TITLES[group]);
  const out = [];
  out.push("# Aura3D CLI reference");
  out.push("");
  out.push("<!-- Generated by tools/docs/gen-cli-reference.mjs from `aura3d help --json`. Do not edit by hand; run `node tools/docs/gen-cli-reference.mjs`. -->");
  out.push("");
  out.push(`Every command of \`${catalog.package}\` (bins: ${catalog.bins.map((b) => `\`${b}\``).join(", ")}), generated from the CLI's own catalog. The same text is printed by \`aura3d help <command>\` and \`aura3d <command> --help\`; \`aura3d help --json\` prints the catalog this page is built from. Task-oriented guides: [cli-asset-tools.md](cli-asset-tools.md) (optimise, merge clips, skin checks, fal generation, conversion) and [docs/agents/asset-workflow.md](../agents/asset-workflow.md).`);
  out.push("");
  out.push("Capability label: CLI asset pipeline. Commands marked **monorepo** need files from an Aura3D repository checkout; run elsewhere they stop with exit 2 and say which file is missing.");
  out.push("");
  out.push("## Exit codes and global flags");
  out.push("");
  out.push("| Exit | Meaning |");
  out.push("| --- | --- |");
  for (const [code, meaning] of Object.entries(catalog.exitCodes)) out.push(`| ${code} | ${escapeCell(meaning)} |`);
  out.push("");
  for (const flag of catalog.globalFlags) out.push(`- \`${flag.flag}\`: ${flag.description}`);
  out.push("- `--json` (where a command's usage lists it): print one JSON object instead of text.");
  out.push("");
  out.push("## Command index");
  out.push("");
  out.push("| Command | What it does | Monorepo-only |");
  out.push("| --- | --- | --- |");
  for (const group of groupNames) {
    for (const command of groups.get(group)) {
      const summary = command.summary.replace(/ \(monorepo\)$/, "");
      out.push(`| [\`aura3d ${command.name}\`](#${anchor(command.name)}) | ${escapeCell(summary)} | ${command.monorepoOnly ? escapeCell(command.monorepoOnly.replace(/^monorepo-only/, "yes")) : ""} |`);
    }
  }
  for (const group of groupNames) {
    out.push("");
    out.push(`## ${title(group)}`);
    for (const command of groups.get(group)) {
      out.push("");
      out.push(`<a id="${anchor(command.name)}"></a>`);
      out.push("");
      out.push(`### \`aura3d ${command.name}\``);
      out.push("");
      out.push(command.summary.replace(/ \(monorepo\)$/, ""));
      if (command.monorepoOnly) {
        out.push("");
        out.push(`**Monorepo:** ${command.monorepoOnly}.`);
      }
      out.push("");
      out.push("```text");
      out.push(command.usage.replace(/\s+$/, ""));
      out.push("```");
      const flags = ownFlags(command);
      if (flags.length) {
        out.push("");
        out.push(`Flags: ${flags.map((f) => `\`${f}\``).join(", ")}.`);
      }
    }
  }
  out.push("");
  out.push("## Codemods");
  out.push("");
  out.push("Run with `aura3d codemod <name> <glob> [--write] [--dry-run] [--report]` (`migrate lighting` and `migrate three` are also top-level commands).");
  out.push("");
  out.push("| Codemod | What it rewrites | Monorepo-only |");
  out.push("| --- | --- | --- |");
  for (const mod of catalog.codemods) out.push(`| \`${mod.name}\` | ${escapeCell(mod.description)} | ${mod.monorepoOnly ? "yes" : ""} |`);
  out.push("");
  return out.join("\n");
}

/** Every `aura3d ...` / `npx @aura3d/cli@x ...` invocation inside code spans or fenced blocks of a doc. */
function invocations(text) {
  const found = [];
  let inFence = false;
  text.split("\n").forEach((line, index) => {
    if (line.trimStart().startsWith("```")) { inFence = !inFence; return; }
    const spans = inFence ? [line] : [...line.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    for (const span of spans) {
      // An invocation ends at a shell separator or where the next one starts (`aura3d a x, aura3d b y`).
      for (const m of span.matchAll(/(?:^|[\s(])(?:aura3d|npx @aura3d\/cli@[\w.-]+)\s+([^|;&#`]*?)(?=,?\s+(?:aura3d|npx @aura3d\/cli@[\w.-]+)\s|[|;&#`]|$)/g)) found.push({ line: index + 1, rest: m[1] });
      // Bare sub-command spans in prose (`assets convert in.fbx --out out.glb`).
      if (!inFence && /^(?:assets|animation)\s+[a-z][\w-]*(?:\s|$)/.test(span)) found.push({ line: index + 1, rest: span });
    }
  });
  return found;
}

function verifyDocs(catalog, files) {
  const byName = new Map(catalog.commands.map((c) => [c.name, c]));
  const global = new Set(["--help", "--version", "--json", "-h", "-v"]);
  const problems = [];
  let checked = 0;
  for (const file of files) {
    const text = readFileSync(path.resolve(file), "utf8");
    for (const { line, rest } of invocations(text)) {
      const words = rest.trim().split(/\s+/);
      if (!words[0] || words[0].startsWith("-") || !/^[a-z]/.test(words[0])) continue;
      const two = `${words[0]} ${words[1] ?? ""}`;
      const command = byName.get(two) ?? byName.get(words[0]);
      if (!command && words.length === 1 && catalog.commands.some((c) => c.name.startsWith(`${words[0]} `))) { checked++; continue; } // a command group (`aura3d assets`)
      if (!command) {
        problems.push(`${file}:${line}: unknown command "aura3d ${two.trim()}"`);
        continue;
      }
      checked++;
      if (command.name === "animation scene" || command.name === "help") continue; // delegates to the project script / takes command names
      const allowed = new Set([...ownFlags(command), ...global]);
      for (const m of rest.matchAll(/(?<![\w-])--[a-z0-9][a-z0-9-]*/gi)) {
        if (!allowed.has(m[0])) problems.push(`${file}:${line}: "aura3d ${command.name}" has no flag ${m[0]}`);
      }
    }
  }
  return { checked, problems };
}

const argv = process.argv.slice(2);
const catalog = loadCatalog(argv);
const verifyAt = argv.indexOf("--verify-docs");
if (verifyAt >= 0) {
  const files = argv.slice(verifyAt + 1).filter((a, i, all) => !a.startsWith("--") && all[i - 1] !== "--from");
  const { checked, problems } = verifyDocs(catalog, files);
  for (const p of problems) console.error(p);
  console.log(JSON.stringify({ ok: problems.length === 0, files: files.length, invocations: checked, problems: problems.length }));
  process.exit(problems.length ? 1 : 0);
}
const markdown = render(catalog);
if (argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== markdown) {
    console.error("docs/api/cli-reference.md is stale: run node tools/docs/gen-cli-reference.mjs");
    process.exit(1);
  }
  console.log(JSON.stringify({ ok: true, commands: catalog.commands.length }));
} else {
  writeFileSync(OUT, markdown);
  console.log(JSON.stringify({ ok: true, wrote: path.relative(ROOT, OUT), commands: catalog.commands.length, codemods: catalog.codemods.length }));
}
