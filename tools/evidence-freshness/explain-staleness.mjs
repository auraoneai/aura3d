#!/usr/bin/env node
/**
 * `explain-staleness`: say exactly why a retained artifact is not current.
 *
 * ## Why a command, not just a gate
 *
 * When the Aura Clash first frame went stale, the failure surfaced as a red boolean. A boolean tells you
 * to re-run something; it does not tell you *which* dependency moved, nor whether re-running can help at
 * all. This prints, per artifact, every dependency that changed and every producer conflict, so the
 * remedy is derivable from the output instead of guessed.
 *
 * It also reports the two structural conditions that no amount of regeneration fixes:
 *
 * - **ownership conflicts**: two producers claiming one authoritative path
 * - **ordering cycles**: producer A binding a hash of a file producer B rewrites
 *
 * Usage:
 *   node tools/evidence-freshness/explain-staleness.mjs
 *   node tools/evidence-freshness/explain-staleness.mjs --json
 *   node tools/evidence-freshness/explain-staleness.mjs --write   # retains the audit artifact
 *   node tools/evidence-freshness/explain-staleness.mjs --route showcase-turbo-drift-circuit
 */
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  createConfigFingerprint,
  createProducerFingerprint,
  createRendererFingerprint,
  explainArtifactStaleness,
  findProducerOrderingCycles,
  findProducerOwnershipConflicts,
  hashFileIfPresent,
  sha256
} from "./index.mjs";
import { DOCUMENTED_PRODUCER_ORDER, PRODUCER_ORDERING_GRAPH, PRODUCER_OWNERSHIP } from "./producer-registry.mjs";
import { writeJsonArtifactAtomically } from "./index.mjs";

const args = process.argv.slice(2);
const asJson = args.includes("--json");
const write = args.includes("--write");
/** Retained audit path, owned by this producer in `producer-registry.mjs`. */
const RETAINED_REPORT_PATH = "tests/reports/evidence-freshness/staleness-audit.json";
const routeFilter = readFlag(args, "--route");
const root = resolve(readFlag(args, "--root") ?? process.cwd());

function readFlag(argv, flag) {
  const index = argv.indexOf(flag);
  return index >= 0 ? argv[index + 1] : undefined;
}

function readJson(absolutePath) {
  try {
    return JSON.parse(readFileSync(absolutePath, "utf8"));
  } catch {
    return undefined;
  }
}

/**
 * Route ids that publish a route-primary probe.
 *
 * Filtered by the producer's own requirement rule rather than "every gated route". `showcase-index` is a gated route
 * with no primary assets, so the producer never writes a probe for it -- and reporting it as `unbound` accused a
 * correctly-absent artifact of being stale. A staleness report that flags files which are not supposed to exist
 * trains readers to skim it, which is the failure this tooling exists to prevent.
 *
 * A route whose probe is *expected* but missing still reports, because `readJson` returns undefined and the artifact
 * is then correctly `unbound`.
 */
function routeIds() {
  const gates = readJson(resolve(root, "tools/showcase-library/route-gates.json"));
  const ids = (gates?.routes ?? [])
    .filter((route) => Boolean(route?.id))
    .filter((route) => Boolean(route.primaryAssets?.length) || route.requiresRoutePrimaryProbe === true)
    /*
     * Skip routes whose retained evidence is deliberately frozen.
     *
     * `retainedEvidenceFrozen: true` means producers must *not* regenerate the artifact -- it is a preserved record of
     * a superseded route. (The two game-layer-proof routes were the original frozen pair; they have since been
     * deleted as discontinued examples.) Reporting frozen evidence as
     * stale is not a finding: it is unfalsifiable by construction, because the only remedy the report implies
     * (regenerate) is the one thing the freeze forbids. Two such entries were the last "not provably current"
     * artifacts, and treating them as defects would have made a clean report permanently unreachable.
     */
    .filter((route) => route.retainedEvidenceFrozen !== true)
    .map((route) => route.id);
  return routeFilter ? ids.filter((id) => id === routeFilter) : ids;
}

/** Frozen route ids, reported separately so the freeze is visible rather than silently skipped. */
function frozenRouteIds() {
  const gates = readJson(resolve(root, "tools/showcase-library/route-gates.json"));
  return (gates?.routes ?? [])
    .filter((route) => route?.id && route.retainedEvidenceFrozen === true)
    .map((route) => route.id);
}

const probeModule = await import(resolve(root, "tools/showcase-library/route-primary-probes.mjs")).catch(() => undefined);

const rendererFingerprint = createRendererFingerprint(root);
/*
 * Read the producer version from the producer, never from a copy here.
 *
 * A hardcoded "1.0" in this explainer reported a producer-version mismatch against a probe generated by
 * producer 1.1 -- the explainer was wrong, not the artifact. A staleness tool that invents its own
 * expectation is worse than none, so the version is imported from the module that defines it.
 */
const producerFingerprint = createProducerFingerprint(
  "tools/showcase-library/route-primary-probes.mjs",
  probeModule?.ROUTE_PRIMARY_PROBE_PRODUCER_VERSION ?? "unknown",
  root
);

/**
 * Recompute the dependency set a route-primary probe should be bound to.
 *
 * This deliberately includes dimensions the current probe does **not** yet record (renderer fingerprint,
 * producer version, camera/viewport config). Those surface as `unbound` rather than as passes, which is
 * the honest reading: an artifact that does not record a dependency cannot be invalidated by it.
 */
function currentDependenciesForRoute(routeId, probe) {
  const appDir = resolve(root, "apps", routeId);
  const dependencies = [];

  const routeSourceHash = probe?.sourceHash;
  const actualSourceHash = computeRouteSourceHash(routeId);
  if (actualSourceHash) dependencies.push({ kind: "route-source", id: routeId, hash: actualSourceHash });

  const gateHash = hashFileIfPresent(resolve(root, "tools/showcase-library/route-gates.json"));
  if (gateHash) dependencies.push({ kind: "route-gate-config", id: "route-gates.json", hash: gateHash });

  /*
   * Use the probe's own narrowing rule rather than a whole-file hash, or this explainer reports a cycle the producer
   * has already eliminated -- the composition-owned `gameAssetPairEvidence` block is not a probe dependency.
   */
  const healthPath = resolve(appDir, "route-health.json");
  const healthHash = existsSync(healthPath)
    ? probeModule?.hashRouteHealthDependency?.(healthPath) ?? hashFileIfPresent(healthPath)
    : undefined;
  if (healthHash) dependencies.push({ kind: "route-health", id: `${routeId}/route-health.json`, hash: healthHash });

  for (const asset of probe?.primaryAssets ?? []) {
    const manifestHash = readManifestAssetHash(asset?.id);
    if (manifestHash) dependencies.push({ kind: "primary-asset", id: String(asset.id), hash: manifestHash });
  }

  dependencies.push({ kind: "renderer-fingerprint", id: "agent-api+assets", hash: rendererFingerprint });
  dependencies.push({ kind: "producer-version", id: "route-primary-probes", hash: producerFingerprint });

  if (probe?.viewport) {
    dependencies.push({ kind: "viewport-contract", id: routeId, hash: createConfigFingerprint(probe.viewport) });
  }

  const screenshot = resolve(root, "tests/reports/showcase-route-primary-probes", `${routeId}.png`);
  const screenshotHash = hashFileIfPresent(screenshot);
  if (screenshotHash) dependencies.push({ kind: "screenshot", id: `${routeId}.png`, hash: screenshotHash });

  return { dependencies, routeSourceHash };
}

/** Mirror of the probe producer's own source hashing, so the two are comparable. */
function computeRouteSourceHash(routeId) {
  const appDir = resolve(root, "apps", routeId);
  if (!existsSync(appDir)) return undefined;
  // Reuse the producer's implementation rather than re-deriving its file selection.
  try {
    return probeModule?.createRouteSourceHash?.(routeId, root);
  } catch {
    return undefined;
  }
}

function readManifestAssetHash(assetId) {
  if (!assetId) return undefined;
  const manifest = readJson(resolve(root, "aura.assets.json"));
  return manifest?.assets?.find((entry) => entry.id === assetId)?.hash;
}


/**
 * Build the freshness binding a probe *implicitly* carries today.
 *
 * The probe records `sourceHash`, `routeGateHash` and `routeHealthHash` plus per-asset `manifestHash`.
 * Translating those into the dependency vocabulary lets one explainer cover both the bindings that exist
 * and the ones that are missing, without pretending the missing ones pass.
 */
function bindingFromProbe(routeId, probe) {
  if (!probe) return undefined;
  const dependencies = [];
  if (probe.sourceHash) dependencies.push({ kind: "route-source", id: routeId, hash: probe.sourceHash });
  if (probe.routeGateHash) {
    dependencies.push({ kind: "route-gate-config", id: "route-gates.json", hash: probe.routeGateHash });
  }
  if (probe.routeHealthHash) {
    dependencies.push({ kind: "route-health", id: `${routeId}/route-health.json`, hash: probe.routeHealthHash });
  }
  for (const asset of probe.primaryAssets ?? []) {
    if (asset?.manifestHash) dependencies.push({ kind: "primary-asset", id: String(asset.id), hash: asset.manifestHash });
  }
  if (probe.renderedProbe?.sha256) {
    dependencies.push({ kind: "screenshot", id: `${routeId}.png`, hash: probe.renderedProbe.sha256 });
  }
  if (probe.freshness?.dependencies) {
    /*
     * A probe carrying an explicit binding wins -- but the screenshot digest still lives in
     * `renderedProbe.sha256` rather than in the dependency list, so it is folded in here. Otherwise the
     * explainer reports the screenshot as `unbound` on a probe that does in fact bind it.
     */
    const explicit = probe.freshness.dependencies;
    const hasScreenshot = explicit.some((dependency) => dependency.kind === "screenshot");
    return {
      ...probe.freshness,
      dependencies: hasScreenshot || !probe.renderedProbe?.sha256
        ? explicit
        : [...explicit, { kind: "screenshot", id: `${routeId}.png`, hash: probe.renderedProbe.sha256 }]
    };
  }
  return {
    schema: "aura3d-evidence-freshness/1.0",
    artifact: `tests/reports/showcase-route-primary-probes/${routeId}.json`,
    producer: { id: "route-primary-probes", version: "inferred", fingerprint: undefined },
    generatedAt: probe.generatedAt,
    dependencies
  };
}

const ownershipConflicts = findProducerOwnershipConflicts(PRODUCER_OWNERSHIP);
/*
 * Pass the documented order so a legitimate DAG edge is not reported as a cycle. Composition depending on the probe's
 * output is correct sequencing; only an edge the order fails to satisfy is a defect.
 */
const orderingCycles = findProducerOrderingCycles(PRODUCER_ORDERING_GRAPH, DOCUMENTED_PRODUCER_ORDER);

const artifacts = [];
for (const routeId of routeIds()) {
  const artifactPath = `tests/reports/showcase-route-primary-probes/${routeId}.json`;
  const probe = readJson(resolve(root, artifactPath));
  const { dependencies } = currentDependenciesForRoute(routeId, probe);
  const relevantCycles = orderingCycles.filter((cycle) => cycle.paths.some((path) => path.includes(routeId)) ||
    cycle.paths.some((path) => path.includes("route-health.json")));
  artifacts.push(explainArtifactStaleness({
    artifactPath,
    binding: bindingFromProbe(routeId, probe),
    currentDependencies: dependencies,
    producerConflicts: relevantCycles.map((cycle) => ({ path: cycle.paths.join(", "), detail: cycle.detail }))
  }));
}

const frozenRoutes = frozenRouteIds();

const report = {
  schema: "aura3d-explain-staleness/1.0",
  generatedAt: new Date().toISOString(),
  rendererFingerprint,
  /** Routes excluded because their retained evidence is deliberately frozen. */
  frozenRoutes,
  ownershipConflicts,
  orderingCycles,
  artifacts,
  staleArtifactCount: artifacts.filter((artifact) => !artifact.fresh).length
};

/*
 * Retain the audit as an artifact, not just console output.
 *
 * ## Why this was a gap
 *
 * WS6 requires each evidence artifact to establish 14 things, the last being "stale reason if rejected". Every
 * other field is recorded in the probes themselves; this one existed **only as console text and a `--json` stream
 * nobody captured**. So the freshness verdict -- the judgement the whole evidence system exists to produce -- was
 * the single evidence class with no durable record, and a release reviewer had to re-run the tool and trust the
 * terminal rather than read a retained file.
 *
 * Written through `writeJsonArtifactAtomically` and declared in the producer registry, so the freshness audit is
 * held to the same ownership and atomicity rules it enforces on everything else. It would be incoherent for the
 * arbiter of retained evidence to be the one producer exempt from those rules.
 */
if (write) {
  writeJsonArtifactAtomically(resolve(root, RETAINED_REPORT_PATH), report);
}

if (asJson) {
  console.log(JSON.stringify(report, null, 2));
} else {
  console.log(`renderer fingerprint: ${rendererFingerprint}`);
  if (ownershipConflicts.length === 0) console.log("producer ownership: no conflicting authoritative paths");
  for (const conflict of ownershipConflicts) console.log(`OWNERSHIP CONFLICT  ${conflict.detail}`);
  if (orderingCycles.length === 0) console.log("producer ordering: no cycles");
  for (const cycle of orderingCycles) console.log(`ORDERING CYCLE      ${cycle.detail}`);
  if (frozenRoutes.length > 0) {
    console.log(`frozen (evidence deliberately preserved, not regenerated): ${frozenRoutes.join(", ")}`);
  }
  console.log("");
  for (const artifact of artifacts) {
    if (artifact.fresh) {
      console.log(`FRESH   ${artifact.artifact}`);
      continue;
    }
    console.log(`${artifact.unbound ? "UNBOUND" : "STALE  "} ${artifact.artifact}`);
    for (const reason of artifact.reasons) {
      console.log(`  - [${reason.status}] ${reason.kind}/${reason.id}: ${reason.detail}`);
    }
  }
  console.log(`\n${report.staleArtifactCount} of ${artifacts.length} artifact(s) are not provably current.`);
}
