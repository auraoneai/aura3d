#!/usr/bin/env -S node_modules/.bin/tsx
/**
 * Deterministic generator for Aura's `softbox` environment (structured studio
 * for metal and glass; see SoftboxEnvironmentScene.ts).
 *
 *   1. rasterize sampleSoftboxEnvironment into six 128 px float faces, scaled
 *      so the solid-angle mean radiance equals the neutral exposure target
 *      (NEUTRAL_FLOOR_RADIANCE): diffuse brightness matches `neutral`, the
 *      difference is purely in the specular structure;
 *   2. GGX-prefilter the mip chain (128 Hammersley samples per texel);
 *   3. project the unfiltered faces onto SH9;
 *   4. write public/aura-environments/softbox.{specular.ktx2,sh9.f32,manifest.json}
 *      and the self-contained embedded copy
 *      packages/rendering/src/environment/softboxEmbedded.ts (no fetch needed).
 *
 * Usage: node_modules/.bin/tsx tools/environments/bake-softbox.ts [--check]
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { constants, gzipSync } from "node:zlib";
import { NEUTRAL_FLOOR_RADIANCE } from "../../packages/rendering/src/environment/probeBuild.ts";
import { projectCubeToSH9 } from "../../packages/rendering/src/environment/SphericalHarmonics.ts";
import { sampleSoftboxEnvironment } from "../../packages/rendering/src/environment/SoftboxEnvironmentScene.ts";
import { faceUvToDir, prefilterCubeGGX } from "../../packages/rendering/src/environment/workers/cpuPrefilter.ts";
import { encodeNeutralKtx2 } from "./bake-neutral.ts";

export const SOFTBOX_FACE_SIZE = 128;
export const SOFTBOX_BAKE_SAMPLES = 128;

function buildFaces(faceSize: number, exposure: number): Float32Array[] {
  const faces: Float32Array[] = [];
  for (let f = 0; f < 6; f += 1) {
    const face = new Float32Array(faceSize * faceSize * 4);
    for (let y = 0; y < faceSize; y += 1) {
      for (let x = 0; x < faceSize; x += 1) {
        const dir = faceUvToDir(f, ((x + 0.5) / faceSize) * 2 - 1, ((y + 0.5) / faceSize) * 2 - 1);
        const [r, g, b] = sampleSoftboxEnvironment(dir as [number, number, number]);
        const i = (y * faceSize + x) * 4;
        face[i] = r * exposure; face[i + 1] = g * exposure; face[i + 2] = b * exposure; face[i + 3] = 1;
      }
    }
    faces.push(face);
  }
  return faces;
}

export function deriveSoftboxExposure(faceSize = SOFTBOX_FACE_SIZE): number {
  const unit = Array.from({ length: 6 }, () => new Float32Array(faceSize * faceSize * 4).fill(1));
  const unitDc = projectCubeToSH9(unit, faceSize)[0]!;
  const dc = projectCubeToSH9(buildFaces(faceSize, 1), faceSize)[0]!;
  return (NEUTRAL_FLOOR_RADIANCE * unitDc) / dc;
}

function main(): void {
  const check = process.argv.includes("--check");
  const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const exposure = deriveSoftboxExposure();
  const faces = buildFaces(SOFTBOX_FACE_SIZE, exposure);
  const prefiltered = prefilterCubeGGX({ faceSize: SOFTBOX_FACE_SIZE, faces }, { samples: SOFTBOX_BAKE_SAMPLES });
  const sh9 = projectCubeToSH9(faces, SOFTBOX_FACE_SIZE);
  const ktx2 = encodeNeutralKtx2(SOFTBOX_FACE_SIZE, prefiltered.levels);
  const shBytes = Buffer.from(sh9.buffer, sh9.byteOffset, sh9.byteLength);
  const sha = (b: Uint8Array) => createHash("sha256").update(b).digest("hex");
  const manifest = JSON.stringify({
    name: "softbox",
    source: "procedural",
    faceSize: SOFTBOX_FACE_SIZE,
    mipCount: prefiltered.mipCount,
    format: "E5B9G9R9_UFLOAT_PACK32",
    specular: "softbox.specular.ktx2",
    sh9: "softbox.sh9.f32",
    sha256: { specular: sha(ktx2), sh9: sha(shBytes) },
    license: "CC0",
    tags: ["studio", "metal", "glass", "softbox"],
    bakedBy: "tools/environments/bake-softbox.ts (Aura3D SoftboxEnvironmentScene.ts)",
    exposure,
    samplesPerTexel: SOFTBOX_BAKE_SAMPLES
  }, null, 2);
  const b64 = Buffer.from(gzipSync(ktx2, { level: constants.Z_BEST_COMPRESSION })).toString("base64");
  const lines = (b64.match(/.{1,120}/g) ?? []).map((l) => `  "${l}"`).join(" +\n");
  const shLiteral = Array.from(sh9).map((v) => String(v)).join(", ");
  const embedded = `// GENERATED by tools/environments/bake-softbox.ts. Do not edit.
// Gzip + base64 of the baked softbox studio specular cube (KTX2, RGB9E5, ${SOFTBOX_FACE_SIZE} px, ${prefiltered.mipCount} mips) and its SH9:
// lets a published-package app bind the softbox environment with no /aura-environments fetch and no copied file.
export const SOFTBOX_SPECULAR_SHA256 = "${sha(ktx2)}";
export const SOFTBOX_FACE_SIZE = ${SOFTBOX_FACE_SIZE};
export const SOFTBOX_SH9 = [${shLiteral}] as const;
export const SOFTBOX_SPECULAR_GZIP_BASE64 =
${lines};
`;
  const outputs = new Map<string, Uint8Array | string>([
    ["public/aura-environments/softbox.specular.ktx2", ktx2],
    ["public/aura-environments/softbox.sh9.f32", shBytes],
    ["public/aura-environments/softbox.manifest.json", manifest],
    ["packages/rendering/src/environment/softboxEmbedded.ts", embedded]
  ]);
  const stale: string[] = [];
  for (const [path, value] of outputs) {
    const bytes = typeof value === "string" ? Buffer.from(value) : Buffer.from(value.buffer, value.byteOffset, value.byteLength);
    let current: Buffer | undefined;
    try { current = readFileSync(join(root, path)); } catch { current = undefined; }
    if (current && Buffer.compare(current, bytes) === 0) continue;
    stale.push(path);
    if (!check) writeFileSync(join(root, path), bytes);
  }
  if (check && stale.length > 0) throw new Error(`softbox environment is stale: ${stale.join(", ")}`);
  console.log(check ? "softbox environment matches the generator" : `wrote ${stale.length ? stale.join(", ") : "nothing (already current)"}; exposure ${exposure}; embedded base64 ${b64.length} chars`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
