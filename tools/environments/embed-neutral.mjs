#!/usr/bin/env node
// Regenerates packages/rendering/src/environment/neutralEmbedded.ts from the baked neutral specular cube.
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync, constants } from "node:zlib";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const src = readFileSync(join(root, "public/aura-environments/neutral.specular.ktx2"));
const manifest = JSON.parse(readFileSync(join(root, "public/aura-environments/neutral.manifest.json"), "utf8"));
const sha = createHash("sha256").update(src).digest("hex");
if (sha !== manifest.sha256.specular) throw new Error(`neutral.specular.ktx2 sha256 ${sha} does not match its manifest`);
const gz = gzipSync(src, { level: constants.Z_BEST_COMPRESSION });
const b64 = gz.toString("base64");
const lines = b64.match(/.{1,120}/g).map((l) => `  "${l}"`).join(" +\n");
const out = `// GENERATED by tools/environments/embed-neutral.mjs from public/aura-environments/neutral.specular.ktx2. Do not edit.
// Gzip + base64 of the baked neutral room specular cube (KTX2, RGB9E5, 256 px, 5 mips): lets a published-package app
// bind the default neutral environment with no /aura-environments fetch and no copied file.
export const NEUTRAL_SPECULAR_SHA256 = "${sha}";
export const NEUTRAL_SPECULAR_GZIP_BASE64 =
${lines};
`;
writeFileSync(join(root, "packages/rendering/src/environment/neutralEmbedded.ts"), out);
console.log(`embedded neutral specular: ${src.length} -> gzip ${gz.length} -> base64 ${b64.length} bytes`);
