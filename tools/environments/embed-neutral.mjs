#!/usr/bin/env node
// Regenerates packages/rendering/src/environment/neutralEmbedded.ts from the baked neutral specular cube.
// The bake is Monte-Carlo (128 samples per texel, about 1% neighbour noise), so the embedded copy drops mantissa bits
// below that noise: 4 bits on mip 0 (the sharp reflection), 5 on the blurred mips. Exponents and layout are unchanged.
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync, constants } from "node:zlib";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

export const DROPPED_MANTISSA_BITS = [4, 5, 5, 5, 5];

/**
 * Round the three 9-bit mantissas of an RGB9E5 word, keeping the exponent: keep (9 - bits) significant bits of the
 * largest channel (fewer bits are dropped for near-black texels whose peak mantissa is small), clamped to 511.
 */
export function quantizeRgb9e5(word, bits) {
  const r = word & 511, g = (word >>> 9) & 511, b = (word >>> 18) & 511;
  const peakBits = 32 - Math.clz32(Math.max(r, g, b));
  const drop = Math.min(bits, Math.max(0, peakBits - (9 - bits)));
  if (drop === 0) return word >>> 0;
  const round = (1 << drop) >> 1;
  const q = (m) => Math.min(511, ((m + round) >> drop) << drop);
  return (((word >>> 27) << 27) | (q(b) << 18) | (q(g) << 9) | q(r)) >>> 0;
}

/** The KTX2 bytes with every mip level quantized per DROPPED_MANTISSA_BITS; header and level index are untouched. */
export function quantizeCube(ktx2) {
  const out = Buffer.from(ktx2);
  const view = new DataView(out.buffer, out.byteOffset, out.byteLength);
  const levelCount = view.getUint32(40, true);
  const dfdEnd = view.getUint32(48, true) + view.getUint32(52, true);
  const kvdEnd = view.getUint32(56, true) + view.getUint32(60, true);
  const indexOff = (Math.max(68, dfdEnd, kvdEnd) + 3) & ~3;
  for (let level = 0; level < levelCount; level += 1) {
    const offset = Number(view.getBigUint64(indexOff + level * 24, true));
    const length = Number(view.getBigUint64(indexOff + level * 24 + 8, true));
    const bits = DROPPED_MANTISSA_BITS[Math.min(level, DROPPED_MANTISSA_BITS.length - 1)];
    for (let at = offset; at < offset + length; at += 4) view.setUint32(at, quantizeRgb9e5(view.getUint32(at, true), bits), true);
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
  const src = readFileSync(join(root, "public/aura-environments/neutral.specular.ktx2"));
  const manifest = JSON.parse(readFileSync(join(root, "public/aura-environments/neutral.manifest.json"), "utf8"));
  const sourceSha = createHash("sha256").update(src).digest("hex");
  if (sourceSha !== manifest.sha256.specular) throw new Error(`neutral.specular.ktx2 sha256 ${sourceSha} does not match its manifest`);
  const embedded = quantizeCube(src);
  const embeddedSha = createHash("sha256").update(embedded).digest("hex");
  const gz = gzipSync(embedded, { level: constants.Z_BEST_COMPRESSION });
  const b64 = gz.toString("base64");
  const lines = b64.match(/.{1,120}/g).map((l) => `  "${l}"`).join(" +\n");
  const out = `// GENERATED by tools/environments/embed-neutral.mjs from public/aura-environments/neutral.specular.ktx2. Do not edit.
// Gzip + base64 of the baked neutral room specular cube (KTX2, RGB9E5, 256 px, 5 mips) with the mantissas rounded to
// ${DROPPED_MANTISSA_BITS.map((b) => 9 - b).join("/")} bits per mip (below the bake's own Monte-Carlo noise): lets a published-package app bind the default
// neutral environment with no /aura-environments fetch and no copied file.
export const NEUTRAL_SPECULAR_SOURCE_SHA256 = "${sourceSha}";
export const NEUTRAL_SPECULAR_SHA256 = "${embeddedSha}";
export const NEUTRAL_SPECULAR_MANTISSA_BITS_DROPPED = [${DROPPED_MANTISSA_BITS.join(", ")}] as const;
export const NEUTRAL_SPECULAR_GZIP_BASE64 =
${lines};
`;
  writeFileSync(join(root, "packages/rendering/src/environment/neutralEmbedded.ts"), out);
  console.log(`embedded neutral specular: ${src.length} -> gzip ${gz.length} -> base64 ${b64.length} bytes (source file ${out.length} bytes)`);
}
