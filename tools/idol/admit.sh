#!/usr/bin/env bash
# Admit an Idol-generated GLB into aura.assets.json / public/aura-assets / src/aura-assets.ts under a repo-wide lock,
# so parallel agents never interleave read-modify-write of the shared manifest.
#   tools/idol/admit.sh <path/to/key.glb> <assetKey> <role> [extra assets-add args...]
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
glb="$1"; key="$2"; role="$3"; shift 3
[ "$role" = background ] && role=set-dressing   # assets add has no "background" role
lock="$root/artifacts/idol/.admit.lock"
mkdir -p "$root/artifacts/idol"
got=0
for _ in $(seq 1 900); do if mkdir "$lock" 2>/dev/null; then got=1; break; fi; sleep 1; done
[ "$got" = 1 ] || { echo "admit lock timeout (stale? remove $lock if no admission is running)" >&2; exit 1; }
trap 'rmdir "$lock" 2>/dev/null || true' EXIT
cd "$root"
node packages/aura3d-cli/dist/cli.js assets add "$glb" --name "$key" --type model --role "$role" \
  --quality candidate --license "LicenseRef-fal-idol-generated" --license-name "fal.ai generated output (speridlabs/idol/max)" \
  --license-raw "Generated by AuraOne through the authenticated fal.ai API with speridlabs/idol/max (commercial use listed as supported); prompts name no brand, logo or real person. Provenance: <glb>.idol.json." \
  --source-family idol \
  --license-url "https://fal.ai/models/speridlabs/idol/max" --source-page "https://fal.ai/models/speridlabs/idol/max" \
  --author "AuraOne (generated with speridlabs/idol/max on fal.ai)" --retrieved-at "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$@" 2>&1 | grep -v '^objc\['
