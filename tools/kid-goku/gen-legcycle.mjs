// Samples the hero GLB's leg-bone local rotations for the run and walk clips into legcycle.ts
// usage: node tools/kid-goku/gen-legcycle.mjs
import fs from "node:fs";
import path from "node:path";

const glb = path.resolve("examples/kid-goku-beyond-the-clouds-port/assets/meshy/hero.glb");
const out = path.resolve("examples/kid-goku-beyond-the-clouds-port/legcycle.ts");
const b = fs.readFileSync(glb);
const jl = b.readUInt32LE(12);
const j = JSON.parse(b.slice(20, 20 + jl).toString());
const bin = b.slice(20 + jl + 8);
const read = (i) => {
  const a = j.accessors[i], v = j.bufferViews[a.bufferView];
  const n = { SCALAR: 1, VEC3: 3, VEC4: 4 }[a.type];
  const base = (v.byteOffset || 0) + (a.byteOffset || 0), stride = v.byteStride || n * 4;
  const d = new Float32Array(a.count * n);
  for (let k = 0; k < a.count; k++) for (let c = 0; c < n; c++) d[k * n + c] = bin.readFloatLE(base + k * stride + c * 4);
  return d;
};
const slerp = (a, c, t) => {
  let d = a[0] * c[0] + a[1] * c[1] + a[2] * c[2] + a[3] * c[3];
  if (d < 0) { c = c.map((x) => -x); d = -d; }
  if (d > 0.9995) { const r = a.map((x, i) => x + (c[i] - x) * t); const l = Math.hypot(...r); return r.map((x) => x / l); }
  const th = Math.acos(d), s = Math.sin(th), w1 = Math.sin((1 - t) * th) / s, w2 = Math.sin(t * th) / s;
  return a.map((x, i) => x * w1 + c[i] * w2);
};
const sample = (times, vals, t) => {
  const last = times.length - 1;
  if (t <= times[0]) return Array.from(vals.slice(0, 4));
  if (t >= times[last]) return Array.from(vals.slice(last * 4, last * 4 + 4));
  let k = 0; while (times[k + 1] < t) k++;
  const f = (t - times[k]) / (times[k + 1] - times[k]);
  return slerp(Array.from(vals.slice(k * 4, k * 4 + 4)), Array.from(vals.slice((k + 1) * 4, (k + 1) * 4 + 4)), f);
};
const BONES = ["LeftUpLeg", "LeftLeg", "RightUpLeg", "RightLeg"];
const SAMPLES = 24;
const r6 = (x) => Math.round(x * 1e6) / 1e6;
const clips = {};
for (const clipName of ["run", "walk"]) {
  const anim = j.animations.find((a) => a.name === clipName);
  const duration = Math.max(...anim.samplers.map((s) => j.accessors[s.input].max[0]));
  const bones = {};
  for (const bone of BONES) {
    const node = j.nodes.findIndex((n) => n.name === bone);
    const ch = anim.channels.find((c) => c.target.node === node && c.target.path === "rotation");
    const s = anim.samplers[ch.sampler], times = read(s.input), vals = read(s.output);
    const frames = [];
    for (let k = 0; k < SAMPLES; k++) frames.push(sample(times, vals, (k / SAMPLES) * duration).map(r6));
    bones[bone] = frames;
  }
  const sampleVec3 = (times, vals, t) => {
    const last = times.length - 1;
    if (t <= times[0]) return Array.from(vals.slice(0, 3));
    if (t >= times[last]) return Array.from(vals.slice(last * 3, last * 3 + 3));
    let k = 0; while (times[k + 1] < t) k++;
    const f = (t - times[k]) / (times[k + 1] - times[k]);
    return [0, 1, 2].map((c) => vals[k * 3 + c] + (vals[(k + 1) * 3 + c] - vals[k * 3 + c]) * f);
  };
  const track = (name, path) => {
    const node = j.nodes.findIndex((n) => n.name === name);
    const ch = anim.channels.find((c) => c.target.node === node && c.target.path === path);
    const sm = anim.samplers[ch.sampler];
    return [read(sm.input), read(sm.output)];
  };
  const extras = { feet: {}, hipsR: [], hipsT: [] };
  for (const foot of ["LeftFoot", "RightFoot"]) {
    const [times, vals] = track(foot, "rotation");
    extras.feet[foot] = Array.from({ length: SAMPLES }, (_, k) => sample(times, vals, (k / SAMPLES) * duration).map(r6));
  }
  { const [times, vals] = track("Hips", "rotation"); extras.hipsR = Array.from({ length: SAMPLES }, (_, k) => sample(times, vals, (k / SAMPLES) * duration).map(r6)); }
  { const [times, vals] = track("Hips", "translation"); extras.hipsT = Array.from({ length: SAMPLES }, (_, k) => sampleVec3(times, vals, (k / SAMPLES) * duration).map(r6)); }
  clips[clipName] = { duration: r6(duration), bones, ...extras };
}
const RIG_NODES = ["Hips", "LeftUpLeg", "LeftLeg", "LeftFoot", "RightUpLeg", "RightLeg", "RightFoot"];
const rig = {};
for (const name of RIG_NODES) {
  const n = j.nodes.find((x) => x.name === name);
  rig[name] = { t: n.translation.map(r6), r: n.rotation.map(r6) };
}
const armature = j.nodes.find((n) => n.name === "Armature");
const posAcc = j.accessors[j.meshes[0].primitives[0].attributes.POSITION];
const meshHeight = posAcc.max[1] - posAcc.min[1];
const src = `// Generated by tools/kid-goku/gen-legcycle.mjs from assets/meshy/hero.glb. Do not edit.\nexport const LEG_SAMPLES = ${SAMPLES};\nexport const LEG_BONES = ${JSON.stringify(BONES)} as const;\nexport type LegBone = (typeof LEG_BONES)[number];\nexport interface LegClip { readonly duration: number; readonly bones: Readonly<Record<LegBone, readonly (readonly [number, number, number, number])[]>> }\nexport type Q4 = readonly [number, number, number, number];\nexport interface GaitClip extends LegClip { readonly feet: Readonly<Record<"LeftFoot" | "RightFoot", readonly Q4[]>>; readonly hipsR: readonly Q4[]; readonly hipsT: readonly (readonly [number, number, number])[] }\nexport const LEG_CLIPS: Readonly<Record<"run" | "walk", GaitClip>> = ${JSON.stringify(clips)} as never;\n/** Rest transforms of the hips and leg chain (glTF node units: centimetres under the 0.01 Armature), the Armature scale and the mesh height in model units (the hero node is fitted to 1.5 m). */\nexport const HERO_RIG = ${JSON.stringify({ armatureScale: armature.scale[0], meshHeight: r6(meshHeight), nodes: rig })} as never as { readonly armatureScale: number; readonly meshHeight: number; readonly nodes: Readonly<Record<"Hips" | "LeftUpLeg" | "LeftLeg" | "LeftFoot" | "RightUpLeg" | "RightLeg" | "RightFoot", { readonly t: readonly [number, number, number]; readonly r: Q4 }>> };\n`;
fs.writeFileSync(out, src);
console.log("wrote", out, src.length, "bytes");
