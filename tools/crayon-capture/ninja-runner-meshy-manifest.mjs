#!/usr/bin/env node
// Writes examples/ninja-runner-port/assets/meshy/manifest.ts: sha256 + bounding size/min for every GLB in that folder.
// Run from the repo root: node tools/crayon-capture/ninja-runner-meshy-manifest.mjs
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const require = createRequire(new URL("../../package.json", import.meta.url));
const { NodeIO } = require("@gltf-transform/core");
const { ALL_EXTENSIONS } = require("@gltf-transform/extensions");
const { MeshoptDecoder } = require("meshoptimizer");
const dir = new URL("../../examples/ninja-runner-port/assets/meshy/", import.meta.url).pathname;
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ "meshopt.decoder": MeshoptDecoder });
const out = {};
for (const f of readdirSync(dir).filter((n) => n.endsWith(".glb")).sort()) {
  const id = f.replace(/\.glb$/, "");
  const buf = readFileSync(dir + f);
  const doc = await io.readBinary(new Uint8Array(buf));
  /* raw POSITION bounds (the engine re-grounds a loaded model so its base sits at the node origin; characters keep their own scale) */
  const min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
  let tris = 0;
  for (const mesh of doc.getRoot().listMeshes()) for (const p of mesh.listPrimitives()) {
    const a = p.getAttribute("POSITION"); const lo = a.getMin([]), hi = a.getMax([]);
    for (let i = 0; i < 3; i++) { min[i] = Math.min(min[i], lo[i]); max[i] = Math.max(max[i], hi[i]); }
    tris += (p.getIndices()?.getCount() ?? a.getCount()) / 3;
  }
  out[id] = { sha256: createHash("sha256").update(buf).digest("hex"), bytes: buf.length, size: [0, 1, 2].map((i) => +(max[i] - min[i]).toFixed(3)), min: min.map((v) => +v.toFixed(3)), triangles: Math.round(tris) };
}
const CHARACTERS = new Set(["hero", "soldier", "brute", "sage"]);
const propIds = Object.keys(out).filter((k) => !CHARACTERS.has(k));
const ts = `// Generated by tools/crayon-capture/ninja-runner-meshy-manifest.mjs: do not edit by hand.\nexport type PropId = ${propIds.map((k) => JSON.stringify(k)).join(" | ")};\nexport interface MeshyEntry { readonly sha256: string; readonly bytes: number; readonly size: readonly [number, number, number]; readonly min: readonly [number, number, number]; readonly triangles: number }\nexport const MESHY_MANIFEST = ${JSON.stringify(out, null, 2)} as unknown as Record<PropId, MeshyEntry> & Record<string, MeshyEntry>;\n`;
writeFileSync(dir + "manifest.ts", ts);
console.log(Object.entries(out).map(([k, v]) => `${k} ${v.bytes}B ${v.triangles}tri size=${v.size} min=${v.min}`).join("\n"));
