#!/usr/bin/env tsx
/**
 * Digest every evidence/look-specs/<game>.json into evidence/look-specs/SUMMARY.md (one row per game).
 *   pnpm exec tsx tools/crayon-capture/look-dump-summary.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", ".."), "evidence", "look-specs");
type J = Record<string, any>;

const rows: string[] = [];
for (const f of fs.readdirSync(dir).filter((n) => n.endsWith(".json") && !n.endsWith(".features.json")).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) as J;
  const ph: J = j.phases?.mid ?? j.phases?.early ?? {};
  const r: J = ph.renderers?.[0] ?? {};
  const cam: J = ph.camera ?? {};
  const lights = (ph.lights ?? []) as J[];
  const lightStr = lights.length === 0 ? "none" : [...new Set(lights.map((l) => l.type))].map((t) => `${lights.filter((l) => l.type === t).length}x${t.replace("Light", "")}`).join(" ");
  const post = j.postChain?.composers?.length ? `composer(${j.postChain.composers.length})` : j.postChain?.nodePipelines?.length ? "node-pipeline" : "none";
  const inv: J[] = j.inventory?.entries ?? [];
  const kinds = new Map<string, number>();
  for (const e of inv) kinds.set(e.kind, (kinds.get(e.kind) ?? 0) + 1);
  const bg = ph.background ? JSON.stringify(ph.background).slice(0, 36) : "-";
  rows.push(
    `| ${j.game} | ${Object.keys(j.phases ?? {}).join("/")} | ${r.size ? r.size.join("x") : "-"} | ${r.toneMappingName ?? "-"} ${r.exposure ?? ""} | ${r.shadowMap?.enabled ? r.shadowMap.type : "off"} | ${cam.ortho ? "ortho" : `fov ${cam.fov ?? "-"}`} | ${lightStr} | ${ph.fog ? ph.fog.type ?? "fog" : "none"} | \`${bg}\` | ${post} | ${j.materials?.rows?.length ?? 0} | ${inv.length} (${[...kinds].map(([k, n]) => `${k}:${n}`).join(" ")}) | ${(j.errors ?? []).length} |`
  );
}
const md = `# Look-spec summary\n\nGenerated by \`tools/crayon-capture/look-dump-summary.ts\` from the per-game specs in this directory.\n\n| Game | Phases | Canvas | Tone map | Shadows | Camera | Lights | Fog | Background | Post | Materials | Inventory | Errors |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n${rows.join("\n")}\n`;
fs.writeFileSync(path.join(dir, "SUMMARY.md"), md);
process.stdout.write(md);
