/**
 * B1 three.js asset bridge: Aura3D source emission.
 *
 * Two files per import, split by ownership:
 * - `<name>.bridge.ts` is generated and rewritten on every regeneration. It
 *   holds the typed model node, the native lights, camera, background and
 *   output taken from the three.js scene, plus the stable node ids.
 * - `<name>.scene.ts` is native source written once and never overwritten.
 *   Authors add behaviour, extra nodes, material overrides or hidden nodes
 *   there; because it addresses the bridge by stable id and material name,
 *   regenerating the GLB with the same generator, parameters and seed keeps
 *   those edits valid.
 */

import type { BridgeLight, BridgeSceneData } from "./contract.js";

function lit(value: unknown): string {
  return JSON.stringify(value);
}

function tuple(v: readonly number[]): string {
  return `[${v.map((n) => String(n)).join(", ")}]`;
}

function lightExpr(light: BridgeLight): string {
  const name = lit(light.id);
  switch (light.kind) {
    case "ambient":
      return `lights.ambient({ name: ${name}, color: ${lit(light.color)}, intensity: ${light.intensity} })`;
    case "hemisphere":
      return `lights.hemisphere({ name: ${name}, skyColor: ${lit(light.color)}, groundColor: ${lit(light.groundColor ?? "#444444")}, intensity: ${light.intensity}${light.position ? `, position: ${tuple(light.position)}` : ""} })`;
    case "directional":
      return `lights.directional({ name: ${name}, color: ${lit(light.color)}, intensity: ${light.intensity}, position: ${tuple(light.position ?? [3, 4, 3])}${light.target ? `, target: ${tuple(light.target)}` : ""}, shadow: ${light.shadow === true} })`;
    case "point":
      return `lights.point({ name: ${name}, color: ${lit(light.color)}, intensity: ${light.intensity}, position: ${tuple(light.position ?? [0, 2, 0])}${light.distance ? `, distance: ${light.distance}` : ""}${light.decay !== undefined ? `, decay: ${light.decay}` : ""}${light.shadow ? ", shadow: true" : ""} })`;
    case "spot":
      return `lights.spot({ name: ${name}, color: ${lit(light.color)}, intensity: ${light.intensity}, position: ${tuple(light.position ?? [0, 4, 0])}${light.target ? `, target: ${tuple(light.target)}` : ""}${light.distance ? `, distance: ${light.distance}` : ""}${light.decay !== undefined ? `, decay: ${light.decay}` : ""}, angle: ${light.angle ?? 0.5}, penumbra: ${light.penumbra ?? 0}${light.shadow ? ", shadow: true" : ""} })`;
  }
}

export interface EmitBridgeOptions {
  readonly assetKey: string;
  /** Import specifier of the typed asset module from the emitted files (no extension). */
  readonly assetsImport: string;
  readonly regenerateCommand: string;
}

export function emitBridgeModule(data: BridgeSceneData, options: EmitBridgeOptions): string {
  const camera = data.camera;
  const custom = data.customMaterials ?? [];
  const n = camelName(data.name);
  const imports = ["camera", "lights", "model", ...(custom.length > 0 ? ["material"] : []), ...(data.environment ? ["environments"] : []), "type AuraModelMaterialOverride", "type AuraModelOptions", "type AuraOutputOptions"];
  const lines = [
    `// GENERATED by \`aura3d import-three\`. Do not edit: regeneration rewrites this file.`,
    `// Regenerate: ${options.regenerateCommand}`,
    `// Native edits belong in ./${data.name}.scene.ts, keyed by the stable ids below.`,
    `import { ${imports.join(", ")} } from "@aura3d/engine";`,
    `import { assets } from ${lit(options.assetsImport)};`,
    ``,
    `/** Stable node ids (glTF node names) in the bridged GLB, in traversal order. */`,
    `export const ${camelName(data.name)}NodeIds = ${lit(data.nodeIds)} as const;`,
    `export type ${pascalName(data.name)}NodeId = (typeof ${camelName(data.name)}NodeIds)[number];`,
    `/** Material slot names in the bridged GLB (targets for model({ materialOverrides })). */`,
    `export const ${camelName(data.name)}Materials = ${lit(data.materials)} as const;`,
    `/** Nodes the three.js scene had hidden; exported anyway and hidden again here. */`,
    `export const ${camelName(data.name)}HiddenNodes: readonly ${pascalName(data.name)}NodeId[] = ${lit(data.hiddenNodeNames)};`,
    `/** Animation clips exported explicitly from the factory. */`,
    `export const ${camelName(data.name)}Clips = ${lit(data.clips)} as const;`,
    `/** three.js ShaderMaterials carried as material.custom, keyed by their slot name (see the report for what each one approximates). */`,
    ...(custom.length > 0
      ? [`export const ${n}CustomMaterials = {`, ...custom.map((entry) => `  ${lit(entry.name)}: material.custom(${JSON.stringify(entry.spec, null, 2).replace(/\n/g, "\n  ")}),`), `};`]
      : [`export const ${n}CustomMaterials = {};`]),
    `/** Installs each carried shader on its placeholder slot. */`,
    `export const ${n}MaterialOverrides: readonly AuraModelMaterialOverride[] = Object.entries(${n}CustomMaterials).map(([target, custom]) => ({ target, material: custom, replaceTextures: true }));`,
    ``,
    `/** The bridged GLB at its authored world scale. Extra options (materialOverrides, more hidden nodes) merge on top. */`,
    `export function ${camelName(data.name)}Model(options: Omit<AuraModelOptions, "scaleMode"> = {}) {`,
    `  return model(${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(options.assetKey) ? `assets.${options.assetKey}` : `assets[${lit(options.assetKey)}]`}, {`,
    `    name: ${lit(data.name)},`,
    `    scaleMode: "world",`,
    `    castShadow: ${data.castShadow},`,
    `    receiveShadow: ${data.receiveShadow},`,
    `    ...options,`,
    `    hiddenNodeNames: [...${camelName(data.name)}HiddenNodes, ...(options.hiddenNodeNames ?? [])]${custom.length > 0 ? "," : ""}`,
    ...(custom.length > 0 ? [`    materialOverrides: [...${n}MaterialOverrides, ...(options.materialOverrides ?? [])]`] : []),
    `  });`,
    `}`,
    ``,
    `/** Lights from the three.js scene, as native nodes (world-space). */`,
    `export function ${camelName(data.name)}Lights() {`,
    `  return [`,
    ...data.lights.map((light) => `    ${lightExpr(light)},`),
    ...(data.environment ? [`    environments.neutral({ intensity: ${data.environment.intensity}, background: false }),`] : []),
    `  ];`,
    `}`,
    ``,
    ...(camera
      ? [`export const ${camelName(data.name)}Camera = camera.perspective({ position: ${tuple(camera.position)}, target: ${tuple(camera.target)}, fov: ${camera.fov}, near: ${camera.near}, far: ${camera.far} });`]
      : [`export const ${camelName(data.name)}Camera = undefined;`]),
    `export const ${camelName(data.name)}Background: string | undefined = ${data.background ? lit(data.background) : "undefined"};`,
    `/** three's renderer output carried over so the first import keeps the authored look. */`,
    `export const ${camelName(data.name)}Output: AuraOutputOptions = { toneMapping: ${lit(data.toneMapping)}, exposure: ${data.exposure} };`,
    ``
  ];
  return lines.join("\n");
}

export function emitNativeSceneModule(data: BridgeSceneData): string {
  const n = camelName(data.name);
  return [
    `// Native Aura3D source for the bridged "${data.name}" asset. \`aura3d import-three\` writes this file once`,
    `// and never overwrites it: edit freely. Regeneration only rewrites ./${data.name}.bridge.ts and the GLB.`,
    `import { createAuraApp, scene, type AuraSceneBuilder } from "@aura3d/engine";`,
    `import { ${n}Background, ${n}Camera, ${n}Lights, ${n}Model, ${n}Output } from "./${data.name}.bridge";`,
    ``,
    `export function create${pascalName(data.name)}Scene(): AuraSceneBuilder {`,
    `  const stage = scene(${n}Background ? { background: ${n}Background } : {})`,
    `    .add(${n}Model())`,
    `    .addMany(${n}Lights());`,
    `  return ${n}Camera ? stage.camera(${n}Camera) : stage;`,
    `}`,
    ``,
    `export function mount${pascalName(data.name)}(selector = "#app") {`,
    `  return createAuraApp(selector, { scene: create${pascalName(data.name)}Scene(), output: ${n}Output });`,
    `}`,
    ``
  ].join("\n");
}

export function camelName(name: string): string {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = parts.map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1))).join("");
  return /^[0-9]/.test(joined) ? `_${joined}` : joined || "bridged";
}

export function pascalName(name: string): string {
  const c = camelName(name);
  return c.charAt(0).toUpperCase() + c.slice(1);
}
