/** Return only strong classes; controls, numbers and some marks are not strong. */
export function strongBidiDirection(codePoint: number): "ltr" | "rtl" | undefined {
  let low = 0;
  let high = STRONG_RANGES.length / 2 - 1;
  while (low <= high) {
    const middle = (low + high) >>> 1;
    const start = STRONG_RANGES[middle * 2];
    const endAndDirection = STRONG_RANGES[middle * 2 + 1];
    if (codePoint < start) high = middle - 1;
    else if (codePoint > (endAndDirection >>> 1)) low = middle + 1;
    else return (endAndDirection & 1) === 0 ? "ltr" : "rtl";
  }
  return undefined;
}
