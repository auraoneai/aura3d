/**
 * Aura3D split-sum GGX directional-albedo lookup.
 *
 * Each RG texel stores coefficients A and B for `F0 * A + F90 * B`.
 * The horizontal and vertical texel centers represent perceptual roughness
 * and N·V respectively; both axes are linear and the texture clamps at its
 * edges. Integration uses the isotropic GGX normal distribution (alpha =
 * roughness²), height-correlated Smith masking, and Schlick's fifth-power
 * Fresnel factor. With H sampled from D(H) (N·H), the Monte Carlo contribution
 * to the reflected-hemisphere integral is G(V,L) (V·H)/((N·V)(N·H)), split
 * into (1-Fc) and Fc, where Fc = (1-V·H)^5. The low-discrepancy samples and
 * binary16 conversion below are specified here to make the data reproducible;
 * no external engine or precomputed table is used.
 */

export const DFG_LUT_SIZE = 16;
export const DFG_LUT_SAMPLES = 65536;

/** Radical inverse in base two, evaluated on an unsigned 32-bit index. */
function radicalInverse(index: number): number {
  let bits = index >>> 0;
  bits = ((bits << 16) | (bits >>> 16)) >>> 0;
  bits = (((bits & 0x55555555) << 1) | ((bits & 0xaaaaaaaa) >>> 1)) >>> 0;
  bits = (((bits & 0x33333333) << 2) | ((bits & 0xcccccccc) >>> 2)) >>> 0;
  bits = (((bits & 0x0f0f0f0f) << 4) | ((bits & 0xf0f0f0f0) >>> 4)) >>> 0;
  bits = (((bits & 0x00ff00ff) << 8) | ((bits & 0xff00ff00) >>> 8)) >>> 0;
  return bits / 4294967296;
}

/**
 * Evaluate the two GGX split-sum coefficients by Hammersley quadrature.
 * Inputs are finite, unit-interval values; sample counts are deliberately
 * bounded so a caller cannot accidentally launch an unbounded CPU job.
 */
export function integrateGgxDfg(roughness: number, ndotv: number, samples = DFG_LUT_SAMPLES): readonly [number, number] {
  if (!Number.isFinite(roughness) || roughness < 0 || roughness > 1 ||
      !Number.isFinite(ndotv) || ndotv <= 0 || ndotv > 1) {
    throw new RangeError("GGX DFG roughness must be in [0,1] and N·V in (0,1]");
  }
  if (!Number.isInteger(samples) || samples < 16 || samples > 65536) {
    throw new RangeError("GGX DFG sample count must be an integer in [16,65536]");
  }
  if (roughness === 0) {
    const fc = (1 - ndotv) ** 5;
    return [1 - fc, fc];
  }
  const alpha = roughness * roughness;
  const alpha2 = alpha * alpha;
  const vx = Math.sqrt(Math.max(0, 1 - ndotv * ndotv));
  const gv = Math.sqrt(alpha2 + (1 - alpha2) * ndotv * ndotv);
  let a = 0;
  let b = 0;
  for (let i = 0; i < samples; i += 1) {
    const u = (i + 0.5) / samples;
    const phi = 2 * Math.PI * radicalInverse(i);
    const nh = Math.sqrt((1 - u) / (1 + (alpha2 - 1) * u));
    const radius = Math.sqrt(Math.max(0, 1 - nh * nh));
    const vh = vx * radius * Math.cos(phi) + ndotv * nh;
    if (vh <= 0) continue;
    const nl = 2 * vh * nh - ndotv;
    if (nl <= 0) continue;
    const gl = Math.sqrt(alpha2 + (1 - alpha2) * nl * nl);
    const denominator = nl * gv + ndotv * gl;
    const g2 = 2 * nl * ndotv / Math.max(denominator, 1e-12);
    const weight = g2 * vh / (nh * ndotv);
    const fc = (1 - vh) ** 5;
    a += (1 - fc) * weight;
    b += fc * weight;
  }
  a /= samples;
  b /= samples;
  // A finite quadrature at grazing angles can overshoot unity slightly.
  // Normalizing only that overshoot preserves nonnegative energy bounds.
  const total = a + b;
  return total > 1 ? [a / total, b / total] : [a, b];
}

/** Encode a nonnegative finite number into IEEE 754 binary16, round to nearest. */
function toFloat16(value: number): number {
  if (!Number.isFinite(value) || value < 0) throw new RangeError("DFG coefficient must be nonnegative and finite");
  if (value === 0) return 0;
  if (value >= 65504) return 0x7bff;
  if (value < 2 ** -14) return Math.min(0x0400, Math.round(value / 2 ** -24));
  let exponent = Math.floor(Math.log2(value));
  let mantissa = Math.round((value / 2 ** exponent - 1) * 1024);
  if (mantissa === 1024) { exponent += 1; mantissa = 0; }
  return ((exponent + 15) << 10) | mantissa;
}

/** Reproduce the row-major RG16F lookup, with roughness on X and N·V on Y. */
export function generateDfgLut(): Uint16Array {
  const result = new Uint16Array(DFG_LUT_SIZE * DFG_LUT_SIZE * 2);
  for (let y = 0; y < DFG_LUT_SIZE; y += 1) {
    for (let x = 0; x < DFG_LUT_SIZE; x += 1) {
      const roughness = (x + 0.5) / DFG_LUT_SIZE;
      const ndotv = (y + 0.5) / DFG_LUT_SIZE;
      const [a, b] = integrateGgxDfg(roughness, ndotv);
      const offset = (y * DFG_LUT_SIZE + x) * 2;
      result[offset] = toFloat16(a);
      result[offset + 1] = toFloat16(b);
    }
  }
  return result;
}

