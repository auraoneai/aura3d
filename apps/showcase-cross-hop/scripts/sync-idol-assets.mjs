#!/usr/bin/env node
// Writes src/aura-assets.idol.ts: the Idol image-to-3D models Cross Hop renders (tools/idol/specs/cross-hop.json),
// copied from the repo-root src/aura-assets.ts (written by tools/idol/admit.sh). Importing the root module would pull
// the whole multi-megabyte catalog into the page, so only these entries are copied, without their metadata blocks.
// vite.config.ts serves and emits the matching /aura-assets/<key>.<hash>.glb files from the root public/ tree.
//   node apps/showcase-cross-hop/scripts/sync-idol-assets.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(appDir, "../..");
const rootCatalog = resolve(repoRoot, "src/aura-assets.ts");
const specFile = resolve(repoRoot, "tools/idol/specs/cross-hop.json");
const outFile = resolve(appDir, "src/aura-assets.idol.ts");
const KEPT_FIELDS = new Set(["type", "format", "url", "hash", "bounds", "sizeBytes"]);

const keys = JSON.parse(readFileSync(specFile, "utf8")).items.map((i) => i.key);
const lines = readFileSync(rootCatalog, "utf8").split("\n");

function entryBlock(key) {
  const start = lines.indexOf(`  "${key}": {`);
  if (start < 0) return null;
  const end = lines.indexOf("  },", start);
  if (end < 0) throw new Error(`unterminated entry for ${key}`);
  const block = lines.slice(start, end + 1);
  const kept = [block[0]];
  let keep = false;
  for (const line of block.slice(1, -1)) {
    const field = line.match(/^    ([A-Za-z]+):/);
    if (field) keep = KEPT_FIELDS.has(field[1]);
    if (keep) kept.push(line);
  }
  kept.push(block[block.length - 1]);
  return kept.join("\n");
}

const present = [];
const missing = [];
for (const key of keys) (entryBlock(key) ? present : missing).push(key);

const out = [
  "// GENERATED by scripts/sync-idol-assets.mjs from the repo-root src/aura-assets.ts. Do not edit by hand.",
  "// Idol (image-to-3D) models Cross Hop renders; spec: tools/idol/specs/cross-hop.json.",
  'import { defineAuraAssets } from "@aura3d/engine";',
  'import type { AuraAssetDefinition, AuraAssetMap } from "@aura3d/engine";',
  "",
  "type IdolModel = AuraAssetDefinition & { readonly type: \"model\"; readonly format: \"glb\"; readonly url: string; readonly hash: string; readonly bounds: readonly [number, number, number]; };",
  "type IdolAssetDefinitions = {",
  ...present.map((k) => `  readonly "${k}": IdolModel;`),
  "};",
  "",
  "export const idolAssets: AuraAssetMap<IdolAssetDefinitions> = defineAuraAssets({",
  present.map((k) => entryBlock(k)).join("\n").replace(/,\s*$/, ""),
  "} as const);",
  ""
].join("\n");

if (process.argv.includes("--check")) {
  const cur = readFileSync(outFile, "utf8");
  if (cur !== out) { console.error("src/aura-assets.idol.ts is stale; run scripts/sync-idol-assets.mjs"); process.exit(1); }
  console.log(`ok (${present.length} idol assets)`);
} else {
  writeFileSync(outFile, out);
  console.log(`wrote ${present.length} idol assets${missing.length ? `; not admitted yet: ${missing.join(", ")}` : ""}`);
}
