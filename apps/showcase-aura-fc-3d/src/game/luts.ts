// Aura FC 3D — GU47 per-venue display LUTs (WP-19 FC47-P2): a split tone per venue, written as 3-D .cube files.
//
// The LUT is pure data generated from the table below (shadow tint, highlight tint, a gentle S-curve), so the
// committed public/aura-assets/fcLut*.cube files are reproducible: tests/unit/aura-fc-3d/gu47-luts.test.ts regenerates
// each one and compares it byte for byte, and runs the E-C admission check (validateCubeLut). Regenerate with
// `node_modules/.bin/tsx apps/showcase-aura-fc-3d/tools/gen-luts.ts` after editing the table.

import type { VenueId } from "./types";

export interface FcLutSpec {
  /** Added to the shadows (weight (1 - L)^2), linear-ish display RGB offsets. */
  readonly shadow: readonly [number, number, number];
  /** Added to the highlights (weight L^2). */
  readonly highlight: readonly [number, number, number];
  /** S-curve strength around mid grey (0 = none). */
  readonly contrast: number;
  /** Saturation multiplier around the pixel's luma. */
  readonly saturation: number;
}

/** One split tone per venue; Munich and Kyoto differ in hue by design (P2 acceptance: pitch hue >= 8 deg apart). */
export const VENUE_LUTS: Readonly<Record<VenueId, FcLutSpec>> = {
  munich: { shadow: [-0.02, 0.01, 0.06], highlight: [-0.01, 0.01, 0.03], contrast: 0.12, saturation: 0.94 },
  kyoto: { shadow: [0.05, -0.02, 0.05], highlight: [0.04, 0.0, -0.02], contrast: 0.1, saturation: 1.08 },
  favela: { shadow: [0.04, 0.01, -0.03], highlight: [0.05, 0.02, -0.04], contrast: 0.1, saturation: 1.02 },
  lagos: { shadow: [0.02, -0.01, 0.03], highlight: [0.06, 0.02, -0.05], contrast: 0.08, saturation: 1.06 },
  uyuni: { shadow: [0.0, 0.01, 0.04], highlight: [0.03, 0.01, 0.0], contrast: 0.04, saturation: 0.95 },
  glacier: { shadow: [-0.03, 0.03, 0.04], highlight: [-0.01, 0.02, 0.02], contrast: 0.1, saturation: 0.96 }
};

export const FC_LUT_SIZE = 17;

const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v);

/** Apply a venue's grade to one display RGB triple (0..1). */
export function fcLutApply(spec: FcLutSpec, rgb: readonly [number, number, number]): [number, number, number] {
  const [r, g, b] = rgb;
  const l = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  const ws = (1 - l) * (1 - l);
  const wh = l * l;
  const out = [r, g, b].map((c, i) => {
    let v = l + (c - l) * spec.saturation;
    v += spec.shadow[i]! * ws + spec.highlight[i]! * wh;
    // S-curve: blend toward smoothstep by `contrast`
    const s = v * v * (3 - 2 * v);
    return clamp01(v + (clamp01(s) - v) * spec.contrast);
  });
  return [out[0]!, out[1]!, out[2]!];
}

/** The .cube text (red varies fastest, as the format requires). */
export function fcLutCube(venue: VenueId, size = FC_LUT_SIZE): string {
  const spec = VENUE_LUTS[venue];
  const lines = [
    `TITLE "aura-fc-3d ${venue} split tone (GU47 FC47-P2)"`,
    "# generated by apps/showcase-aura-fc-3d/src/game/luts.ts; do not edit by hand",
    `LUT_3D_SIZE ${size}`,
    "DOMAIN_MIN 0 0 0",
    "DOMAIN_MAX 1 1 1"
  ];
  for (let bi = 0; bi < size; bi++) for (let gi = 0; gi < size; gi++) for (let ri = 0; ri < size; ri++) {
    const o = fcLutApply(spec, [ri / (size - 1), gi / (size - 1), bi / (size - 1)]);
    lines.push(o.map((v) => v.toFixed(4)).join(" "));
  }
  return `${lines.join("\n")}\n`;
}
