#!/usr/bin/env node
/**
 * IRON CROWN grade LUTs (GU47 WP-15 IC47-P2): writes the four venue `.cube` LUTs this game authors itself.
 *
 *   node apps/showcase-iron-crown/scripts/make-luts.mjs [outDir]
 *
 * Each LUT is a 17^3 display-referred split tone (shadow tint, highlight tint, saturation) that keeps per-pixel
 * luminance, so the luma bands of the venue barely move while its hue does. Deterministic: same bytes every run.
 * The files are admitted with `aura3d assets add <file.cube> --type lut` (typed as `assets.ironcrownLut*`).
 * Original work for this game (no third-party source), so provenance is "generated by this script".
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SIZE = 17;

/** shadow / highlight: RGB offsets added with weight (1-L)^2 and L^2; sat: saturation multiplier. */
export const IRON_CROWN_LUTS = {
  ironcrownLutDockDusk: { title: "Iron Crown Bangkok dock dusk teal-orange", shadow: [-0.05, 0.02, 0.07], highlight: [0.09, 0.03, -0.07], sat: 1.06 },
  ironcrownLutColosseumOchre: { title: "Iron Crown Colosseum noon ochre", shadow: [0.04, 0.01, -0.06], highlight: [0.1, 0.04, -0.1], sat: 0.96 },
  ironcrownLutAirbaseHaze: { title: "Iron Crown desert airbase sunset haze", shadow: [0.05, -0.03, 0.04], highlight: [0.1, 0.02, -0.08], sat: 1.04 },
  ironcrownLutMonasteryFrost: { title: "Iron Crown Himalayan monastery cold dawn", shadow: [-0.05, 0, 0.07], highlight: [-0.06, 0.01, 0.08], sat: 0.88 }
};

const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;
const clamp01 = (v) => Math.min(1, Math.max(0, v));

/** The graded colour for one input colour (display-referred, 0..1). Exported for the unit test. */
export function gradeColor(spec, r, g, b) {
  const l = luma(r, g, b);
  const ws = (1 - l) * (1 - l);
  const wh = l * l;
  let rr = r + ws * spec.shadow[0] + wh * spec.highlight[0];
  let gg = g + ws * spec.shadow[1] + wh * spec.highlight[1];
  let bb = b + ws * spec.shadow[2] + wh * spec.highlight[2];
  const l2 = luma(rr, gg, bb);
  rr = l2 + (rr - l2) * spec.sat;
  gg = l2 + (gg - l2) * spec.sat;
  bb = l2 + (bb - l2) * spec.sat;
  // Keep the input luminance (the luma bands stay put; only hue and chroma move).
  const shift = l - luma(rr, gg, bb);
  return [clamp01(rr + shift), clamp01(gg + shift), clamp01(bb + shift)];
}

export function cubeText(spec) {
  const lines = [`TITLE "${spec.title}"`, `# Generated by apps/showcase-iron-crown/scripts/make-luts.mjs (GU47 IC47-P2).`, `LUT_3D_SIZE ${SIZE}`];
  for (let bi = 0; bi < SIZE; bi++) {
    for (let gi = 0; gi < SIZE; gi++) {
      for (let ri = 0; ri < SIZE; ri++) {
        const [r, g, b] = gradeColor(spec, ri / (SIZE - 1), gi / (SIZE - 1), bi / (SIZE - 1));
        lines.push(`${r.toFixed(4)} ${g.toFixed(4)} ${b.toFixed(4)}`);
      }
    }
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = resolve(process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "art-src", "luts"));
  mkdirSync(outDir, { recursive: true });
  for (const [id, spec] of Object.entries(IRON_CROWN_LUTS)) {
    writeFileSync(join(outDir, `${id}.cube`), cubeText(spec));
    console.log(join(outDir, `${id}.cube`));
  }
}
