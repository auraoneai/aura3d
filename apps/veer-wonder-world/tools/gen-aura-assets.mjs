#!/usr/bin/env node
// Generates src/aura-assets.ts from tools/wonder-assets.json. Never edit src/aura-assets.ts by hand.
//
//   node tools/gen-aura-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(app, "tools", "wonder-assets.json"), "utf8"));
const VALID_ROLES = new Set(["character", "vehicle", "prop", "background"]);

if (!Array.isArray(spec.assets) || spec.assets.length !== 65) {
  throw new Error(`wonder-assets.json: expected 65 asset entries, got ${Array.isArray(spec.assets) ? spec.assets.length : "non-array"}`);
}

const seen = new Set();
for (const entry of spec.assets) {
  if (typeof entry?.key !== "string" || entry.key.trim() === "") {
    throw new Error("wonder-assets.json: asset entry has empty key");
  }
  if (seen.has(entry.key)) {
    throw new Error(`wonder-assets.json: duplicate key "${entry.key}"`);
  }
  seen.add(entry.key);
  if (!VALID_ROLES.has(entry.role)) {
    throw new Error(`wonder-assets.json: ${entry.key} has invalid role "${String(entry.role)}"`);
  }
  if (typeof entry.heightM !== "number" || !Number.isFinite(entry.heightM) || entry.heightM <= 0) {
    throw new Error(`wonder-assets.json: ${entry.key} has invalid heightM "${String(entry.heightM)}"`);
  }
  if (typeof entry.face !== "boolean") {
    throw new Error(`wonder-assets.json: ${entry.key} has invalid face flag "${String(entry.face)}"`);
  }
}

const q = (value) => JSON.stringify(value);
const lines = [];
lines.push("// GENERATED by tools/gen-aura-assets.mjs from tools/wonder-assets.json. Do not edit by hand.");
lines.push("export const MODEL_KEYS = [");
for (const entry of spec.assets) {
  lines.push(`  ${q(entry.key)},`);
}
lines.push("] as const;");
lines.push("");
lines.push("export type ModelKey = (typeof MODEL_KEYS)[number];");
lines.push('export type AssetRole = "character" | "vehicle" | "prop" | "background";');
lines.push("");
lines.push("export interface ModelInfo {");
lines.push("  readonly heightM: number;");
lines.push("  readonly role: AssetRole;");
lines.push("  readonly face: boolean;");
lines.push("  readonly procedural: true;");
lines.push("}");
lines.push("");
lines.push("export const MODEL_INFO: Readonly<Record<ModelKey, ModelInfo>> = {");
for (const entry of spec.assets) {
  lines.push(`  ${entry.key}: { heightM: ${entry.heightM}, role: ${q(entry.role)}, face: ${entry.face}, procedural: true },`);
}
lines.push("};");
lines.push("");
lines.push("export const PROCEDURAL_MODELS: readonly ModelKey[] = MODEL_KEYS;");
lines.push("");

writeFileSync(join(app, "src", "aura-assets.ts"), lines.join("\n"));
console.log(`aura-assets.ts: ${spec.assets.length} procedural models`);
