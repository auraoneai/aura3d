#!/usr/bin/env node
// Generates src/aura-assets.ts from the admitted models in src/assets/models and their
// provenance records in provenance/models. Never edit src/aura-assets.ts by hand.
//
//   node tools/gen-aura-assets.mjs
//
// Each admitted model has src/assets/models/<key>.<sha8>.glb (written by tools/admit-models.mjs) and
// provenance/models/<key>.json ({ key, sha256, sizeBytes, rigged, clips, heightM, triangles, license, ... }).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const modelsDir = join(app, "src", "assets", "models");
const provDir = join(app, "provenance", "models");
const spec = JSON.parse(readFileSync(join(app, "tools", "wonder-assets.json"), "utf8"));
const review = JSON.parse(readFileSync(join(app, "tools", "model-review.json"), "utf8"));
const procedural = spec.assets.map((a) => a.key).filter((k) => review[k]?.status === "procedural");

const entries = [];
const missing = [];
for (const a of spec.assets) {
  const prov = join(provDir, `${a.key}.json`);
  if (!existsSync(prov)) { missing.push(a.key); continue; }
  const p = JSON.parse(readFileSync(prov, "utf8"));
  const file = !existsSync(modelsDir) ? undefined : readdirSync(modelsDir).find((f) => f.startsWith(`${a.key}.`) && f.endsWith(".glb"));
  if (!file) { missing.push(a.key); continue; }
  const bytes = readFileSync(join(modelsDir, file));
  const sha = createHash("sha256").update(bytes).digest("hex");
  if (sha !== p.sha256) throw new Error(`${a.key}: provenance sha256 ${p.sha256} does not match ${file} (${sha})`);
  entries.push({ key: a.key, file, sha, size: bytes.length, rigged: Boolean(p.rigged), clips: p.clips ?? [], heightM: p.heightM ?? 1, role: a.role, license: p.license });
}

const q = (s) => JSON.stringify(s);
const lines = [];
lines.push("// GENERATED by tools/gen-aura-assets.mjs from provenance/models. Do not edit by hand.");
lines.push("// Every model is an original text-prompt generation (Meshy through Kiro Prism); see provenance/models/*.json.");
lines.push('import { defineModelAssets, type AuraAssetRef } from "@aura3d/engine";');
lines.push("");
lines.push("/** Every model key the app knows about, admitted or not. */");
lines.push(`export const MODEL_KEYS = ${q(spec.assets.map((a) => a.key))} as const;`);
lines.push("export type ModelKey = (typeof MODEL_KEYS)[number];");
lines.push("");
lines.push("export const models = defineModelAssets(");
lines.push("  {");
for (const e of entries) {
  lines.push(`    ${e.key}: { url: new URL(${q(`./assets/models/${e.file}`)}, import.meta.url).pathname, sha256: ${q(e.sha)}, sizeBytes: ${e.size}${e.clips.length ? `, animations: ${q(e.clips)}` : ""} },`);
}
lines.push("  },");
lines.push('  { license: "Meshy-generated output under the AuraOne account plan terms at generation time; original prompts; exclusivity not claimed" }');
lines.push(");");
lines.push("");
lines.push("export interface ModelInfo {");
lines.push("  readonly admitted: boolean;");
lines.push("  readonly rigged: boolean;");
lines.push("  readonly clips: readonly string[];");
lines.push("  /** Height in metres the scene fits the model to by default. */");
lines.push("  readonly heightM: number;");
lines.push("  /** Drawn from scene geometry by design (tools/model-review.json status \"procedural\"), not a missing file. */");
lines.push("  readonly procedural: boolean;");
lines.push("}");
lines.push("");
lines.push("export const MODEL_INFO: Readonly<Record<ModelKey, ModelInfo>> = {");
for (const a of spec.assets) {
  const e = entries.find((x) => x.key === a.key);
  lines.push(`  ${a.key}: { admitted: ${Boolean(e)}, rigged: ${e?.rigged ?? false}, clips: ${q(e?.clips ?? [])}, heightM: ${a.heightM ?? 1}, procedural: ${procedural.includes(a.key)} },`);
}
lines.push("};");
lines.push("");
lines.push("/** Keys drawn procedurally by design (see tools/model-review.json). */");
lines.push(`export const PROCEDURAL_MODELS: readonly ModelKey[] = ${q(procedural)};`);
lines.push("");
lines.push("/** The typed ref of an admitted model, or undefined when the file is not admitted (the scene draws a stand-in). */");
lines.push("export function modelRef(key: ModelKey): AuraAssetRef<\"model\"> | undefined {");
lines.push("  return (models.refs as Readonly<Record<string, AuraAssetRef<\"model\"> | undefined>>)[key];");
lines.push("}");
lines.push("");

writeFileSync(join(app, "src", "aura-assets.ts"), lines.join("\n"));
console.log(`aura-assets.ts: ${entries.length} admitted, ${missing.length} missing${missing.length ? ` (${missing.join(", ")})` : ""}`);
