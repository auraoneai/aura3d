/// <reference types="node" />
// Source guard A02 (audit gap A02; MASTER-PROMPT section 4 code quality): the app's sources narrow types with type
// guards and checked parsing, never by assertion. A static scan of every TypeScript file under src/ (binary media under
// src/assets/ excluded), parsed with the TypeScript compiler so comments and strings never count, fails on any type
// assertion: `expr as T`, `<T>expr`, and each half of `as unknown as T`. `as const` is not a cast and is always
// allowed (as is `satisfies`). The few assertions that remain are listed below with the reason each one is safe;
// the list must stay exact, so removing a cast also means removing its entry.

import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as ts from "typescript";
import { describe, expect, it } from "vitest";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const srcDir = join(appRoot, "src");

interface AllowedCast {
  /** App-relative path. */
  readonly file: string;
  /** The asserted expression and type, whitespace collapsed. */
  readonly expression: string;
  readonly type: string;
  /** How many times this exact assertion appears in the file. */
  readonly count: number;
  readonly reason: string;
}

/**
 * The type assertions src/ keeps (2026-10-29), each with why it cannot lie about the value. Every other assertion is a
 * failure; an entry whose cast is gone is a failure too (stale entries hide nothing, but the list must stay exact).
 */
const ALLOWED_CASTS: readonly AllowedCast[] = [
  {
    file: "src/aura-assets.ts",
    expression: "models.refs",
    type: 'Readonly<Record<string, AuraAssetRef<"model"> | undefined>>',
    count: 1,
    reason:
      "Generated by tools/gen-aura-assets.mjs. Widens the per-key refs of defineModelAssets (keys of admitted models only) " +
      "to a string-keyed lookup with undefined values, so modelRef(key) can ask for an unadmitted key; undefined is the " +
      "handled answer (the stage draws a stand-in)."
  },
  {
    file: "src/characters/character-registry.ts",
    expression: "GESTURES",
    type: "readonly string[]",
    count: 1,
    reason:
      "A widening, not a narrowing: the readonly Gesture[] is read as readonly string[] so includes() accepts the " +
      "unchecked song-motion string inside the isGesture type guard; no value is claimed to be a narrower type."
  },
  {
    file: "src/characters/character-registry.ts",
    expression: "CHARACTER_IDS",
    type: "readonly string[]",
    count: 1,
    reason:
      "A widening, not a narrowing: the readonly CharacterId[] is read as readonly string[] so includes() accepts the " +
      "unchecked string inside the isCharacterId type guard; no value is claimed to be a narrower type."
  },
  {
    file: "src/scenes/spots.ts",
    expression: "Object.keys(SPOTS)",
    type: "readonly SpotId[]",
    count: 1,
    reason:
      "Object.keys is typed string[] for any object; SPOTS is a Record<SpotId, Vec3> literal with no other keys, so its " +
      "keys are exactly the SpotId union."
  }
];

interface CastHit {
  readonly file: string;
  readonly line: number;
  readonly expression: string;
  readonly type: string;
}

function collapse(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

/** Every type assertion in one TypeScript source text (`as const` left out). */
function typeAssertions(file: string, text: string): CastHit[] {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const hits: CastHit[] = [];
  const visit = (node: ts.Node): void => {
    if (ts.isAsExpression(node) || ts.isTypeAssertionExpression(node)) {
      const type = collapse(node.type.getText(source));
      if (type !== "const") {
        const { line } = source.getLineAndCharacterOfPosition(node.getStart(source));
        hits.push({ file, line: line + 1, expression: collapse(node.expression.getText(source)), type });
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return hits;
}

function sourceFiles(dir: string = srcDir, out: string[] = []): string[] {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (path === join(srcDir, "assets")) continue;
      sourceFiles(path, out);
    } else if (name.endsWith(".ts")) {
      out.push(path);
    }
  }
  return out;
}

const HITS: readonly CastHit[] = sourceFiles().flatMap((path) => typeAssertions(relative(appRoot, path).split("\\").join("/"), readFileSync(path, "utf8")));

function keyOf(entry: { readonly file: string; readonly expression: string; readonly type: string }): string {
  return `${entry.file} | ${entry.expression} as ${entry.type}`;
}

describe("A02: no type assertions in src/", () => {
  it("finds assertions the way the compiler sees them (self-check on a sample)", () => {
    const sample = [
      "const a = b as Foo;",
      "const c = <Bar>d;",
      "const e = f as unknown as Baz;",
      "const g = [1, 2] as const;",
      "const h = { x: 1 } satisfies Record<string, number>;",
      "// const i = j as Commented;",
      'const k = "as Quoted";'
    ].join("\n");
    const found = typeAssertions("sample.ts", sample).map((hit) => `${hit.expression} as ${hit.type}`);
    expect(found).toEqual(["b as Foo", "d as Bar", "f as unknown as Baz", "f as unknown"]);
  });

  it("keeps no type assertion beyond the commented allow-list", () => {
    const allowed = new Map(ALLOWED_CASTS.map((entry) => [keyOf(entry), entry.count]));
    const seen = new Map<string, CastHit[]>();
    for (const hit of HITS) seen.set(keyOf(hit), [...(seen.get(keyOf(hit)) ?? []), hit]);
    const unlisted: string[] = [];
    for (const [key, hits] of seen) {
      const limit = allowed.get(key) ?? 0;
      if (hits.length > limit) unlisted.push(...hits.slice(limit).map((hit) => `${hit.file}:${hit.line} ${hit.expression} as ${hit.type}`));
    }
    expect(
      unlisted,
      "Gap A02: narrow with a type guard or a checked parse instead of `as`. A cast that truly cannot lie goes in ALLOWED_CASTS with its reason."
    ).toEqual([]);
  });

  it("keeps the allow-list exact: every entry still matches as many casts as it lists", () => {
    const counts = new Map<string, number>();
    for (const hit of HITS) counts.set(keyOf(hit), (counts.get(keyOf(hit)) ?? 0) + 1);
    const stale = ALLOWED_CASTS.filter((entry) => (counts.get(keyOf(entry)) ?? 0) < entry.count).map((entry) => `${keyOf(entry)} (listed ${entry.count}, found ${counts.get(keyOf(entry)) ?? 0})`);
    expect(stale, "remove or update allow-list entries whose cast is gone").toEqual([]);
    for (const entry of ALLOWED_CASTS) expect(entry.reason.length, keyOf(entry)).toBeGreaterThan(40);
  });
});
