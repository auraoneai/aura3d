#!/usr/bin/env node
// Writes apps/showcase-bunker-zero/src/aura-assets.root.ts: the entries of the root typed catalog (src/aura-assets.ts) this game
// loads, so the page no longer ships the 2.6 MB shared catalog (audit RH-06). Entries are copied verbatim (same url, hash,
// bounds, metadata), so the root aura.assets.json stays the single source of truth. Assets admitted for this game alone stay in
// src/aura-assets.local.ts.
// Run after the root catalog changes: node apps/showcase-bunker-zero/scripts/extract-assets.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rootCatalog = resolve(appDir, "../../src/aura-assets.ts");
const outFile = resolve(appDir, "src/aura-assets.root.ts");

/** every root-catalog key the game reads (main.ts and weapons-view.ts VIEWMODEL_ASSET) */
export const BUNKER_ZERO_ROOT_KEYS = [
  "auroraPadBeacon",
  "blockfallReactorContainmentPylonMeshy",
  "bunkerKeyMeshy",
  "bunkerTreasureMeshy",
  "corridorFireAmmoBoltMeshy",
  "corridorFireAmmoCrateMeshy",
  "corridorMuzzleFlameBurstMeshy",
  "corridorPulseRifleMeshy",
  "fpsEnergyCorePickupMeshy",
  "fpsSciFiCoverCrateMeshy",
  "mechWeaponA",
  "mechWeaponB",
  "pulseNeonGateArchMeshy"
];

const src = readFileSync(rootCatalog, "utf8");
const valuesAt = src.indexOf("defineAuraAssets({");
if (valuesAt < 0) throw new Error("root catalog: defineAuraAssets({ not found");

const typeLines = [];
const valueBlocks = [];
for (const key of BUNKER_ZERO_ROOT_KEYS) {
  const typeMatch = new RegExp(`^  readonly "${key}": .*$`, "m").exec(src.slice(0, valuesAt));
  if (!typeMatch) throw new Error(`root catalog: no type line for ${key}`);
  typeLines.push(typeMatch[0]);
  const start = src.indexOf(`\n  "${key}": {`, valuesAt);
  if (start < 0) throw new Error(`root catalog: no entry for ${key}`);
  const end = src.indexOf("\n  }", start + 1);
  const close = src.slice(end, end + 5).startsWith("\n  },") ? end + 5 : end + 4;
  valueBlocks.push(src.slice(start + 1, close).replace(/,$/, ""));
}

const out = `// Generated by apps/showcase-bunker-zero/scripts/extract-assets.mjs from src/aura-assets.ts — do not edit by hand.
// Bunker Zero loads only these ${BUNKER_ZERO_ROOT_KEYS.length} root entries instead of the shared 1,000+ entry catalog (audit RH-06).
import { defineAuraAssets } from "@aura3d/engine";
import type { AuraAssetDefinition, AuraAssetMap } from "@aura3d/engine";

type BunkerZeroRootAssetDefinitions = {
${typeLines.join("\n")}
};

export const assets: AuraAssetMap<BunkerZeroRootAssetDefinitions> = defineAuraAssets({
${valueBlocks.join(",\n")}
} as const);
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== out) {
    console.error("apps/showcase-bunker-zero/src/aura-assets.root.ts is stale: run node apps/showcase-bunker-zero/scripts/extract-assets.mjs");
    process.exit(1);
  }
  console.log("bunker-zero asset subset is current");
} else {
  writeFileSync(outFile, out);
  console.log(`wrote ${outFile} (${BUNKER_ZERO_ROOT_KEYS.length} assets, ${out.length} bytes)`);
}
