#!/usr/bin/env node
// Writes apps/showcase-bunker-zero/src/aura-assets.root.ts and apps/showcase-bunker-zero/src/aura-assets.local.ts
// from apps/showcase-bunker-zero/aura.assets.json (and any shared root-catalog keys in BUNKER_ZERO_ROOT_KEYS),
// so the page never ships the 2.6 MB shared catalog (audit RH-06) and procedural viewmodels stay typed.
// Run after catalog changes: node apps/showcase-bunker-zero/scripts/extract-assets.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rootCatalog = resolve(appDir, "../../src/aura-assets.ts");
const localManifestFile = resolve(appDir, "aura.assets.json");
const outRootFile = resolve(appDir, "src/aura-assets.root.ts");
const outLocalFile = resolve(appDir, "src/aura-assets.local.ts");

/** Shared root-catalog GLB keys read by Bunker Zero (0 after WP-11 procedural overhaul). */
export const BUNKER_ZERO_ROOT_KEYS = [];

/** Procedural first-person viewmodel keys referenced in `VIEWMODEL_ASSET` (`weapons-view.ts`). */
export const BUNKER_ZERO_PROCEDURAL_KEYS = [
  "bzProceduralPulseCarbine",
  "bzProceduralRocketLauncher",
  "bzProceduralServicePistol"
];

function formatField(name, value) {
  return `    ${name}: ${JSON.stringify(value, null, 2).replace(/\n/g, "\n    ")},`;
}

// 1. Build src/aura-assets.root.ts
const rootTypeLines = [];
const rootValueBlocks = [];
if (BUNKER_ZERO_ROOT_KEYS.length > 0) {
  const src = readFileSync(rootCatalog, "utf8");
  const valuesAt = src.indexOf("defineAuraAssets({");
  if (valuesAt < 0) throw new Error("root catalog: defineAuraAssets({ not found");
  for (const key of BUNKER_ZERO_ROOT_KEYS) {
    const typeMatch = new RegExp(`^  readonly "${key}": .*$`, "m").exec(src.slice(0, valuesAt));
    if (!typeMatch) throw new Error(`root catalog: no type line for ${key}`);
    rootTypeLines.push(typeMatch[0]);
    const start = src.indexOf(`\n  "${key}": {`, valuesAt);
    if (start < 0) throw new Error(`root catalog: no entry for ${key}`);
    const end = src.indexOf("\n  }", start + 1);
    const close = src.slice(end, end + 5).startsWith("\n  },") ? end + 5 : end + 4;
    rootValueBlocks.push(src.slice(start + 1, close).replace(/,$/, ""));
  }
}
for (const key of BUNKER_ZERO_PROCEDURAL_KEYS) {
  rootTypeLines.push(`  readonly "${key}": { readonly id: "${key}"; readonly type: "procedural" };`);
  rootValueBlocks.push(`  "${key}": { id: "${key}", type: "procedural" }`);
}

const outRoot = `// Generated by apps/showcase-bunker-zero/scripts/extract-assets.mjs — do not edit by hand.
// Bunker Zero loads 0 shared root GLBs after WP-11; procedural viewmodel descriptors are typed here.
type BunkerZeroRootAssetDefinitions = {
${rootTypeLines.join("\n")}
};

export const assets: BunkerZeroRootAssetDefinitions = {
${rootValueBlocks.join(",\n")}
};
`;

// 2. Build src/aura-assets.local.ts from aura.assets.json
const manifest = JSON.parse(readFileSync(localManifestFile, "utf8"));
const localEntries = manifest.assets ?? [];
const localLines = [
  `import { defineAuraAssets } from "@aura3d/engine";`,
  `import type { AuraAssetDefinition, AuraAssetMap } from "@aura3d/engine";`,
  "",
  "type AuraGeneratedAssetDefinitions = {",
  ...localEntries.map((asset) => {
    const bounds = asset.bounds ? " readonly bounds: readonly [number, number, number];" : "";
    return `  readonly ${JSON.stringify(asset.id)}: AuraAssetDefinition & { readonly type: ${JSON.stringify(asset.type)}; readonly format: ${JSON.stringify(asset.format)}; readonly url: string; readonly hash: string;${bounds} };`;
  }),
  "};",
  "",
  "export const assets: AuraAssetMap<AuraGeneratedAssetDefinitions> = defineAuraAssets({",
  ...localEntries.map((asset) => {
    const provenance = asset.provenance ? { ...asset.provenance } : undefined;
    if (provenance) delete provenance.generation;
    const metadata = {
      materials: asset.materials,
      animations: asset.animations,
      animationClips: asset.animationClips ? asset.animationClips.map((c) => c.name) : asset.animations,
      ...(asset.animationClips ? { animationClipDetails: asset.animationClips } : {}),
      animationMetadata: asset.animationMetadata,
      humanoid: asset.humanoid?.humanoid ?? false,
      humanoidStatus: asset.humanoid?.status ?? "unknown",
      humanoidConfidence: asset.humanoid?.confidence ?? "low",
      skeleton: asset.skeleton,
      morphTargets: asset.morphTargets,
      hierarchy: asset.hierarchy,
      ...(provenance ? { provenance } : {}),
      ...(asset.modelInspection ? { modelInspection: asset.modelInspection } : {}),
      sourcePath: asset.source,
      outputPath: asset.outputPath,
      license: asset.provenance?.license,
      ...(asset.provenance?.author ? { author: asset.provenance.author } : {}),
      boundsMetadata: asset.boundsMetadata,
      materialMetadata: asset.materialMetadata,
      orientation: asset.orientation,
      nodeNames: asset.nodeNames ?? [],
      textures: asset.textures,
      dependencies: asset.dependencies ?? [],
      thumbnailUrl: asset.thumbnailUrl,
      quality: asset.quality ?? "ungraded",
      role: asset.role ?? "unknown",
      ...(asset.suitabilityReason ? { suitabilityReason: asset.suitabilityReason } : {}),
      ...(asset.renderedProbe ? { renderedProbe: asset.renderedProbe } : {}),
      ...(asset.gameGeometry ? { gameGeometry: asset.gameGeometry } : {})
    };
    return [
      `  ${JSON.stringify(asset.id)}: {`,
      formatField("type", asset.type),
      formatField("format", asset.format),
      formatField("url", asset.url),
      formatField("hash", asset.integrity?.digest ?? asset.hash ?? asset.sha256),
      formatField("bounds", asset.bounds ?? [0, 0, 0]),
      `    sizeBytes: ${asset.sizeBytes},`,
      formatField("metadata", metadata),
      "  },"
    ].join("\n");
  }),
  "} as const);",
  "",
  "export type AuraGeneratedAssets = typeof assets;",
  ""
];
const outLocal = localLines.join("\n");

if (process.argv.includes("--check")) {
  const curRoot = readFileSync(outRootFile, "utf8");
  const curLocal = readFileSync(outLocalFile, "utf8");
  if (curRoot !== outRoot || curLocal !== outLocal) {
    console.error("apps/showcase-bunker-zero asset modules are stale: run node apps/showcase-bunker-zero/scripts/extract-assets.mjs");
    process.exit(1);
  }
  console.log("bunker-zero asset subset is current");
} else {
  writeFileSync(outRootFile, outRoot);
  writeFileSync(outLocalFile, outLocal);
  console.log(`wrote ${outRootFile} (${BUNKER_ZERO_PROCEDURAL_KEYS.length} procedural keys) and ${outLocalFile} (${localEntries.length} local assets)`);
}
