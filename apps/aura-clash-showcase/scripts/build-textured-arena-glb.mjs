#!/usr/bin/env node
/**
 * Build the textured Aura Clash arena GLB.
 *
 * ## Why this script exists
 *
 * `assets/source/arenas/arena-neon-downtown.glb` is the purpose-built arena: 47 nodes carrying
 * streets, sidewalks, six buildings, props, and the route's own authored
 * `AuraClash_Emerald_FloorRail` / `AuraClash_Sign_*` / `AuraClash_*_RimLight` set. It ships
 * **zero images and zero textures**, and 84 of its 131 materials omit `metallicFactor` and
 * `roughnessFactor` entirely.
 *
 * That combination is not merely "untextured", it is unrenderable-looking. In glTF both factors
 * default to **1.0** when absent, and the renderer computes the diffuse term as `kd = 1 - metallic`.
 * A fully metallic material with no environment map therefore has *no* diffuse and *no* specular
 * source: it renders black. On top of that, 11 of the base colours are a flat `0.5` grey
 * placeholder that only makes sense as a multiplier against a base-colour map that was never
 * attached. This is the same defect class that hid `arenaRooftopBuilding` for its entire life.
 *
 * The previous mitigation (`build-lightweight-arena-glb.mjs`) took the opposite approach: keep one
 * building, drop the maps, and hand-write measured average factors. That produced a single flat
 * façade -- one mesh node -- which is exactly the "lightweight façade plane" the arena rebuild is
 * meant to replace.
 *
 * Every source map is present locally under
 * `assets/quaternius-source/selected/arena/neon-downtown/gltf/`, so the correct fix is to attach
 * the real maps rather than to average them away.
 *
 * ## What it does
 *
 * 1. Reads the material -> texture assignment from the **source `.gltf` files**, so the mapping is
 *    derived from the asset pack rather than hand-transcribed. `MATERIAL_TEXTURE_SLOTS` below is
 *    generated by this read, not by eye.
 * 2. Re-encodes each referenced map through ImageMagick at `TEXTURE_EDGE` px. The pack ships 2K
 *    maps totalling **82.4 MB**, which is not a web payload; JPEG is used for opaque maps because
 *    `image/jpeg` is core glTF and needs no extension declaration, and PNG is retained only where
 *    the source actually carries alpha.
 * 3. Neutralises the placeholder factors on every material that gains a base-colour map, because a
 *    `0.5` grey or a dark tint factor *multiplies* the map and would darken it twice.
 * 4. Sets `metallicFactor`/`roughnessFactor` to 1.0 on materials that gain an ORM map, which is the
 *    correct identity multiplier when the map supplies the real values.
 * 5. Emits a single self-contained GLB with the images embedded as buffer views.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDir, "..");
const packDir = resolve(appRoot, "assets/quaternius-source/selected/arena/neon-downtown/gltf");
const sourcePath = resolve(appRoot, "assets/source/arenas/arena-neon-downtown.glb");
const outputPath = resolve(appRoot, "assets/source/arenas/arena-neon-downtown-textured.glb");

/**
 * Re-encode edge length. The pack's 2048px maps are tiled architectural detail viewed from a fixed
 * side-on fighting-game camera at 6-9 units, where the building never fills more than roughly a
 * third of frame width. 1024 keeps brick/trim/asphalt detail legible at that framing while cutting
 * the payload by ~4x.
 */
const TEXTURE_EDGE = 1024;
/**
 * Normal maps are re-encoded at half the colour resolution.
 *
 * At the fixed side-on fighting-game camera the buildings sit 6-18 units back and no wall fills more
 * than roughly a third of frame width, so normal-map detail is well below one texel per pixel long
 * before base-colour detail is. The six normal maps were 2.99 MB of a 5.72 MB texture payload -- more
 * than every base-colour and ORM map combined -- which is the wrong allocation for this framing.
 */
const NORMAL_MAP_EDGE = 512;
const JPEG_QUALITY = 88;
/** Normal maps carry direction in chroma, so they are encoded with less chroma loss than colour maps. */
const NORMAL_MAP_QUALITY = 94;

if (!existsSync(sourcePath)) throw new Error(`Missing arena source GLB: ${sourcePath}`);
if (!existsSync(packDir)) throw new Error(`Missing Quaternius source pack: ${packDir}`);

/** Read the authoritative material -> texture-slot assignment out of the source pack's own glTF files. */
function readPackMaterialSlots() {
  const slots = new Map();
  const files = execFileSync("/bin/sh", ["-c", `ls ${JSON.stringify(packDir)}/*.gltf`], { encoding: "utf8" })
    .trim().split("\n").filter(Boolean).sort();
  for (const file of files) {
    const document = JSON.parse(readFileSync(file, "utf8"));
    const images = (document.images ?? []).map((image) => image.uri);
    const textures = document.textures ?? [];
    const resolveUri = (reference) => {
      if (!reference || reference.index === undefined) return undefined;
      const source = textures[reference.index]?.source;
      return source === undefined ? undefined : images[source];
    };
    for (const material of document.materials ?? []) {
      if (!material.name || slots.has(material.name)) continue;
      const pbr = material.pbrMetallicRoughness ?? {};
      const entry = {
        baseColor: resolveUri(pbr.baseColorTexture),
        metallicRoughness: resolveUri(pbr.metallicRoughnessTexture),
        normal: resolveUri(material.normalTexture),
        occlusion: resolveUri(material.occlusionTexture),
        emissive: resolveUri(material.emissiveTexture)
      };
      if (Object.values(entry).some(Boolean)) slots.set(material.name, entry);
    }
  }
  if (slots.size === 0) throw new Error("Source pack declared no textured materials; refusing to write an untextured arena.");
  return slots;
}

const MATERIAL_TEXTURE_SLOTS = readPackMaterialSlots();

/**
 * Window interiors are the one authored addition beyond a faithful re-attach.
 *
 * The pack assigns the lit/dark interior maps as base colour only, so at night the window rows read
 * as flat dark panels and the six buildings collapse into one silhouette. Reusing the same map as an
 * emissive map -- modulating the emissive factor the arena GLB already declares -- is what makes
 * individual lit windows read against the unlit brick. It is a map the asset already contains,
 * applied to a slot the renderer already supports, not invented geometry or fake DOM lighting.
 */
const EMISSIVE_FROM_BASE_COLOR = new Set(["MI_FakeInterior_1", "MI_FakeInterior_2", "MI_FakeInterior_3", "MI_FakeInterior_4"]);

const glb = readFileSync(sourcePath);
if (glb.readUInt32LE(0) !== 0x46546c67) throw new Error("Arena source is not a binary GLB.");
const jsonLength = glb.readUInt32LE(12);
const document = JSON.parse(glb.subarray(20, 20 + jsonLength).toString("utf8"));
const binStart = 20 + jsonLength + 8;
let binary = glb.subarray(binStart, binStart + glb.readUInt32LE(20 + jsonLength));

if ((document.images ?? []).length > 0 || (document.textures ?? []).length > 0) {
  throw new Error("Arena source already carries textures; this builder is for the untextured export.");
}

const sourceAccessorCount = (document.accessors ?? []).length;
const workDir = mkdtempSync(join(tmpdir(), "aura-clash-arena-tex-"));
const encoded = new Map();

/**
 * Re-encode one pack map, keeping PNG only where the alpha channel actually carries data.
 *
 * Declared-channel detection is not enough here: 25 of the 26 referenced maps are tagged `srgba`
 * but their alpha is uniformly 1.0, so trusting `%[channels]` forced lossless PNG for opaque
 * normal/ORM maps and cost 11.5 MB of the payload. Only `T_Street_Decals.png` has real
 * transparency (alpha range 0 - 0.784). So alpha is measured, not declared.
 */
function encodeTexture(uri) {
  const cached = encoded.get(uri);
  if (cached) return cached;
  const inputPath = resolve(packDir, uri);
  if (!existsSync(inputPath)) throw new Error(`Source pack is missing referenced map: ${uri}`);
  const channels = execFileSync("magick", ["identify", "-format", "%[channels]", inputPath], { encoding: "utf8" }).trim();
  const alphaMinimum = channels.includes("a")
    ? Number(execFileSync("magick", [inputPath, "-alpha", "extract", "-format", "%[fx:minima]", "info:"], { encoding: "utf8" }).trim())
    : 1;
  const hasAlpha = alphaMinimum < 0.999;
  const extension = hasAlpha ? "png" : "jpg";
  // Normal maps encode direction in chroma, which JPEG subsamples most aggressively, so they get a
  // higher quality and no chroma subsampling. Colour/ORM maps use the standard quality.
  const isNormalMap = /_Normal\.png$/i.test(uri);
  const outputFile = join(workDir, `${uri.replace(/\.png$/i, "")}.${extension}`);
  const edge = isNormalMap ? NORMAL_MAP_EDGE : TEXTURE_EDGE;
  const args = [inputPath, "-resize", `${edge}x${edge}>`, "-strip"];
  if (hasAlpha) args.push(outputFile);
  else {
    args.push("-alpha", "off", "-quality", String(isNormalMap ? NORMAL_MAP_QUALITY : JPEG_QUALITY));
    if (isNormalMap) args.push("-sampling-factor", "1x1");
    args.push(outputFile);
  }
  execFileSync("magick", args);
  const record = {
    mimeType: hasAlpha ? "image/png" : "image/jpeg",
    bytes: readFileSync(outputFile),
    sourceBytes: statSync(inputPath).size
  };
  encoded.set(uri, record);
  return record;
}

document.images = [];
document.textures = [];
document.samplers = [{ magFilter: 9729, minFilter: 9987, wrapS: 10497, wrapT: 10497 }];
const bufferViews = document.bufferViews ?? [];
const imageIndexByUri = new Map();
const textureIndexByUri = new Map();
const pendingImageBuffers = [];

/** Register one map as an embedded image + texture, deduplicated across every material that uses it. */
function textureIndexFor(uri) {
  const existing = textureIndexByUri.get(uri);
  if (existing !== undefined) return existing;
  const record = encodeTexture(uri);
  const bufferViewIndex = bufferViews.length;
  // Byte offsets are assigned after the full image payload is laid out, so record a placeholder.
  bufferViews.push({ buffer: 0, byteOffset: 0, byteLength: record.bytes.length });
  pendingImageBuffers.push({ bufferViewIndex, bytes: record.bytes });
  const imageIndex = document.images.length;
  document.images.push({ bufferView: bufferViewIndex, mimeType: record.mimeType, name: uri });
  imageIndexByUri.set(uri, imageIndex);
  const textureIndex = document.textures.length;
  document.textures.push({ sampler: 0, source: imageIndex });
  textureIndexByUri.set(uri, textureIndex);
  return textureIndex;
}

const stats = { textured: 0, untouched: 0, baseColorNeutralised: 0, ormIdentity: 0, emissiveMaps: 0 };
const unmatched = [];

for (const material of document.materials ?? []) {
  const baseName = String(material.name ?? "").replace(/\.\d+$/, "");
  const slots = MATERIAL_TEXTURE_SLOTS.get(baseName);
  if (!slots) {
    // Materials the pack itself declares as factor-only (MI_Glass, the authored neon signs and
    // emerald rim) are correct as exported and must not be touched.
    const pbr = material.pbrMetallicRoughness ?? {};
    if (pbr.metallicFactor === undefined || pbr.roughnessFactor === undefined) unmatched.push(material.name);
    stats.untouched += 1;
    continue;
  }
  const pbr = { ...(material.pbrMetallicRoughness ?? {}) };

  if (slots.baseColor) {
    pbr.baseColorTexture = { index: textureIndexFor(slots.baseColor) };
    // A placeholder 0.5 grey or a dark viewport tint multiplies the map. Neutralise it and let the
    // map carry the colour, preserving only alpha.
    const alpha = pbr.baseColorFactor?.[3] ?? 1;
    if (pbr.baseColorFactor && !pbr.baseColorFactor.slice(0, 3).every((channel) => channel === 1)) stats.baseColorNeutralised += 1;
    pbr.baseColorFactor = [1, 1, 1, alpha];
  }
  if (slots.metallicRoughness) {
    pbr.metallicRoughnessTexture = { index: textureIndexFor(slots.metallicRoughness) };
    // 1.0 is the identity multiplier once the ORM map supplies the real values. Leaving these
    // absent is what makes an untextured export render black.
    pbr.metallicFactor = 1;
    pbr.roughnessFactor = 1;
    stats.ormIdentity += 1;
    // ORM packs occlusion in R, so the same map is the correct occlusion source.
    material.occlusionTexture = { index: textureIndexFor(slots.metallicRoughness) };
  } else if (pbr.metallicFactor === undefined || pbr.roughnessFactor === undefined) {
    // No ORM map available: pin explicit non-metallic values rather than inheriting 1.0.
    pbr.metallicFactor = pbr.metallicFactor ?? 0;
    pbr.roughnessFactor = pbr.roughnessFactor ?? 0.85;
  }
  if (slots.normal) material.normalTexture = { index: textureIndexFor(slots.normal) };
  if (slots.occlusion) material.occlusionTexture = { index: textureIndexFor(slots.occlusion) };
  if (slots.emissive) material.emissiveTexture = { index: textureIndexFor(slots.emissive) };
  else if (EMISSIVE_FROM_BASE_COLOR.has(baseName) && slots.baseColor) {
    material.emissiveTexture = { index: textureIndexFor(slots.baseColor) };
    // Raise the declared emissive so a re-mapped window row is visible without blowing out bloom.
    material.emissiveFactor = [0.62, 0.55, 0.42];
    stats.emissiveMaps += 1;
  }

  material.pbrMetallicRoughness = pbr;
  stats.textured += 1;
}

if (unmatched.length > 0) {
  throw new Error(
    `Refusing to write the arena: ${unmatched.length} material(s) have neither a pack texture mapping nor explicit ` +
    `metallic/roughness factors, so they would inherit glTF's 1.0 metallic default and render black: ${unmatched.join(", ")}`
  );
}
if (document.images.length === 0) throw new Error("Refusing to write an arena with zero embedded images.");

/*
 * Geometry payload reduction.
 *
 * The source geometry buffer is 16.3 MB, and most of it is data nothing consumes:
 *
 * - `TEXCOORD_1` (2.22 MB) and `TEXCOORD_2` (0.67 MB): every material in the pack samples
 *   `texCoord: 0` only, so sets 1 and 2 are read by `readTexcoordSets` and then discarded.
 * - `COLOR_0` (3.29 MB) and `COLOR_1` (0.47 MB): 92.8% of `COLOR_0` vertices are exactly white and
 *   the channel is a uniform tint the textured materials now supply. `COLOR_1` is not read by the
 *   loader at all.
 * - Duplicated meshes (~8.5 MB): the pack instances six buildings, four bollards, five floor rails
 *   and more by *copying* vertex data. 11 mesh groups hold byte-identical attributes across 26
 *   nodes, and no bufferView is shared by more than one accessor.
 *
 * Nodes keep their own transforms, so pointing duplicate nodes at one mesh is a pure payload win
 * with no change to what renders.
 */
const DROPPED_ATTRIBUTES = ["TEXCOORD_1", "TEXCOORD_2", "COLOR_0", "COLOR_1"];
const geometryStats = { droppedAttributes: 0, dedupedMeshes: 0, dedupedMaterials: 0, prunedAccessors: 0 };

for (const mesh of document.meshes ?? []) {
  for (const primitive of mesh.primitives ?? []) {
    for (const semantic of DROPPED_ATTRIBUTES) {
      if (primitive.attributes[semantic] !== undefined) {
        delete primitive.attributes[semantic];
        geometryStats.droppedAttributes += 1;
      }
    }
  }
}

/*
 * Deduplicate identical materials first.
 *
 * The pack exports one material *instance* per mesh copy (`MI_RedBrick`, `MI_RedBrick.001`, ...),
 * 131 in total for 24 distinct definitions. Mesh deduplication has to run after this, because two
 * byte-identical building meshes otherwise differ only by pointing at two identical-but-separate
 * materials, and the signature would treat them as distinct. Collapsing materials first is what
 * takes mesh deduplication from 4 groups to the full set.
 */
const materialSignatures = new Map();
const canonicalMaterialIndex = new Map();
for (const [index, material] of (document.materials ?? []).entries()) {
  const { name: _name, ...comparable } = material;
  const signature = stableStringify(comparable);
  const existing = materialSignatures.get(signature);
  if (existing === undefined) materialSignatures.set(signature, index);
  else {
    canonicalMaterialIndex.set(index, existing);
    geometryStats.dedupedMaterials += 1;
  }
}
for (const mesh of document.meshes ?? []) {
  for (const primitive of mesh.primitives ?? []) {
    if (primitive.material === undefined) continue;
    const canonical = canonicalMaterialIndex.get(primitive.material);
    if (canonical !== undefined) primitive.material = canonical;
  }
}

// Point byte-identical meshes at one canonical mesh index. Nodes keep their own transforms.
const meshSignatures = new Map();
const canonicalMeshIndex = new Map();
for (const [index, mesh] of (document.meshes ?? []).entries()) {
  const signature = JSON.stringify((mesh.primitives ?? []).map((primitive) => [
    Object.entries(primitive.attributes).sort().map(([semantic, accessor]) => [semantic, accessorSignature(accessor)]),
    primitive.indices === undefined ? null : accessorSignature(primitive.indices),
    primitive.material ?? null,
    primitive.mode ?? 4
  ]));
  const existing = meshSignatures.get(signature);
  if (existing === undefined) meshSignatures.set(signature, index);
  else {
    canonicalMeshIndex.set(index, existing);
    geometryStats.dedupedMeshes += 1;
  }
}
for (const node of document.nodes ?? []) {
  if (node.mesh === undefined) continue;
  const canonical = canonicalMeshIndex.get(node.mesh);
  if (canonical !== undefined) node.mesh = canonical;
}

/*
 * Rebuild accessors, bufferViews, meshes and materials so only reachable entries survive.
 *
 * Pruning the payload alone is not enough: dropping an attribute or a duplicate mesh leaves
 * orphaned accessors behind, and once the retained views are repacked those orphans point at stale
 * byte offsets. A strict loader that walks `accessors` rather than only the reachable graph would
 * read past the buffer. So the arrays are rebuilt and every index is remapped.
 */
const referencedMeshes = new Set((document.nodes ?? []).flatMap((node) => node.mesh === undefined ? [] : [node.mesh]));
const keptMeshIndices = [...(document.meshes ?? []).keys()].filter((index) => referencedMeshes.has(index));
const meshRemap = new Map(keptMeshIndices.map((index, position) => [index, position]));
const keptMeshes = keptMeshIndices.map((index) => document.meshes[index]);

const usedMaterials = new Set(keptMeshes.flatMap((mesh) => (mesh.primitives ?? []).flatMap((primitive) => primitive.material === undefined ? [] : [primitive.material])));
const keptMaterialIndices = [...(document.materials ?? []).keys()].filter((index) => usedMaterials.has(index));
const materialRemap = new Map(keptMaterialIndices.map((index, position) => [index, position]));

const usedAccessors = new Set(keptMeshes.flatMap((mesh) => (mesh.primitives ?? []).flatMap((primitive) => [
  ...Object.values(primitive.attributes),
  ...(primitive.indices === undefined ? [] : [primitive.indices])
])));
const keptAccessorIndices = [...(document.accessors ?? []).keys()].filter((index) => usedAccessors.has(index));
const accessorRemap = new Map(keptAccessorIndices.map((index, position) => [index, position]));

// Repack the retained geometry views contiguously, then append the image views.
const keptGeometryViews = [...new Set(keptAccessorIndices.map((index) => document.accessors[index].bufferView))].filter((view) => view !== undefined);
const viewRemap = new Map();
const rebuiltViews = [];
let geometryPayload = Buffer.alloc(0);
for (const index of keptGeometryViews) {
  const view = bufferViews[index];
  const start = view.byteOffset ?? 0;
  viewRemap.set(index, rebuiltViews.length);
  rebuiltViews.push({ buffer: 0, byteOffset: geometryPayload.length, byteLength: view.byteLength, ...(view.byteStride ? { byteStride: view.byteStride } : {}) });
  geometryPayload = align(Buffer.concat([geometryPayload, binary.subarray(start, start + view.byteLength)]), 4);
}
let payload = align(geometryPayload, 4);
for (const pending of pendingImageBuffers) {
  viewRemap.set(pending.bufferViewIndex, rebuiltViews.length);
  rebuiltViews.push({ buffer: 0, byteOffset: payload.length, byteLength: pending.bytes.length });
  payload = align(Buffer.concat([payload, pending.bytes]), 4);
}

document.accessors = keptAccessorIndices.map((index) => ({ ...document.accessors[index], bufferView: viewRemap.get(document.accessors[index].bufferView) }));
document.materials = keptMaterialIndices.map((index) => document.materials[index]);
document.meshes = keptMeshes.map((mesh) => ({
  ...mesh,
  primitives: (mesh.primitives ?? []).map((primitive) => ({
    ...primitive,
    attributes: Object.fromEntries(Object.entries(primitive.attributes).map(([semantic, accessor]) => [semantic, accessorRemap.get(accessor)])),
    ...(primitive.indices === undefined ? {} : { indices: accessorRemap.get(primitive.indices) }),
    ...(primitive.material === undefined ? {} : { material: materialRemap.get(primitive.material) })
  }))
}));
document.nodes = (document.nodes ?? []).map((node) => node.mesh === undefined ? node : { ...node, mesh: meshRemap.get(node.mesh) });
for (const image of document.images) image.bufferView = viewRemap.get(image.bufferView);
document.bufferViews = rebuiltViews;
document.buffers = [{ byteLength: payload.length }];
geometryStats.prunedAccessors = sourceAccessorCount - document.accessors.length;
document.asset = { ...(document.asset ?? { version: "2.0" }), generator: "aura-clash build-textured-arena-glb" };

const json = align(Buffer.from(JSON.stringify(document)), 4, 0x20);
const totalLength = 12 + 8 + json.length + 8 + payload.length;
const out = Buffer.alloc(totalLength);
let offset = 0;
out.writeUInt32LE(0x46546c67, offset); offset += 4;
out.writeUInt32LE(2, offset); offset += 4;
out.writeUInt32LE(totalLength, offset); offset += 4;
out.writeUInt32LE(json.length, offset); offset += 4;
out.writeUInt32LE(0x4e4f534a, offset); offset += 4;
json.copy(out, offset); offset += json.length;
out.writeUInt32LE(payload.length, offset); offset += 4;
out.writeUInt32LE(0x004e4942, offset); offset += 4;
payload.copy(out, offset);

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, out);
rmSync(workDir, { recursive: true, force: true });

const sourceMapBytes = [...encoded.values()].reduce((sum, record) => sum + record.sourceBytes, 0);
const embeddedMapBytes = [...encoded.values()].reduce((sum, record) => sum + record.bytes.length, 0);
console.log(`[aura-clash textured arena] Wrote ${outputPath}`);
console.log(`  materials textured: ${stats.textured} | left as authored: ${stats.untouched}`);
console.log(`  base-colour factors neutralised: ${stats.baseColorNeutralised} | ORM identity factors set: ${stats.ormIdentity} | window emissive maps: ${stats.emissiveMaps}`);
console.log(`  embedded images: ${document.images.length} | maps ${(sourceMapBytes / 1e6).toFixed(1)} MB -> ${(embeddedMapBytes / 1e6).toFixed(1)} MB (colour/ORM ${TEXTURE_EDGE}px, normals ${NORMAL_MAP_EDGE}px)`);
console.log(`  geometry: dropped ${geometryStats.droppedAttributes} unused attribute references | deduplicated ${geometryStats.dedupedMeshes} meshes + ${geometryStats.dedupedMaterials} materials`);
console.log(`  pruned: ${geometryStats.prunedAccessors} orphaned accessors | kept ${document.accessors.length} accessors, ${document.meshes.length} meshes, ${document.materials.length} materials, ${document.bufferViews.length} views`);
console.log(`  total GLB: ${(out.length / 1e6).toFixed(2)} MB (source ${(glb.length / 1e6).toFixed(2)} MB)`);

/**
 * Order-independent deep serialisation for structural comparison.
 *
 * `JSON.stringify(value, Object.keys(value).sort())` is not a substitute: passing an array as the
 * second argument makes it a key *whitelist applied at every nesting level*, so nested keys such as
 * `baseColorTexture` and `index` are filtered out. Using it here silently reduced every
 * texture-bearing material to the same signature and collapsed 121 distinct materials into 10 --
 * brick, trim, concrete and asphalt all became the marble interior floor.
 */
function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

/** Content signature for an accessor's backing bytes, used to detect byte-identical duplicate meshes. */
function accessorSignature(accessorIndex) {
  const accessor = document.accessors[accessorIndex];
  const view = bufferViews[accessor.bufferView];
  const start = (view.byteOffset ?? 0) + (accessor.byteOffset ?? 0);
  return `${accessor.componentType}:${accessor.type}:${accessor.count}:${createHash("sha1").update(binary.subarray(start, start + view.byteLength)).digest("hex").slice(0, 16)}`;
}

function align(buffer, alignment, fill = 0) {
  const padding = (alignment - (buffer.length % alignment)) % alignment;
  return padding === 0 ? buffer : Buffer.concat([buffer, Buffer.alloc(padding, fill)]);
}
