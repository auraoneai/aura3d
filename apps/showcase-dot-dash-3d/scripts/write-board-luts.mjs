// Glint Courier: the six per-board display LUTs (GU47 DD47-P3). Procedural and deterministic: each board's .cube is
// a split tone (shadows toward the board's mask hue, highlights toward its lamp), a soft filmic shoulder and a small
// saturation trim, written as a 17^3 3-D LUT that the S10b display grade binds through `colorGrade({ lut })`.
// No generation and no external source: the file is a pure function of BOARD_LUTS below.
//
// Write (from the repo root):  node apps/showcase-dot-dash-3d/scripts/write-board-luts.mjs
// Check only (exit 1 on drift): node apps/showcase-dot-dash-3d/scripts/write-board-luts.mjs --check
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const LUT_SIZE = 17;

/**
 * Per-board grade terms (display-referred 0..1). `shadow` and `highlight` are sRGB hex tints, `split` is how far each
 * end moves toward its tint, `shoulder` rolls the top end off, `saturation` trims chroma after the split.
 */
export const BOARD_LUTS = {
  classic: { title: "Glint Courier classic: green FR-4 under a 3000 K lamp", shadow: "#123a2c", highlight: "#ffc48a", split: 0.16, shoulder: 0.1, saturation: 1.02 },
  spiral: { title: "Glint Courier spiral: purple RF board, gold highlights", shadow: "#2a1650", highlight: "#ffd59a", split: 0.17, shoulder: 0.1, saturation: 1.03 },
  twin: { title: "Glint Courier twin: blue power board, tin and cool shadows", shadow: "#0f2a5c", highlight: "#ffe6c6", split: 0.15, shoulder: 0.08, saturation: 0.98 },
  garden: { title: "Glint Courier garden: white-mask LED board, fresh greens", shadow: "#24402a", highlight: "#fff4dc", split: 0.12, shoulder: 0.14, saturation: 1.08 },
  foundry: { title: "Glint Courier foundry: red heavy-copper board, ember shadows", shadow: "#4a1410", highlight: "#ffb877", split: 0.18, shoulder: 0.1, saturation: 1.0 },
  zerocore: { title: "Glint Courier zerocore: black reactor board, magenta shadows", shadow: "#2c0f34", highlight: "#ffdcb8", split: 0.2, shoulder: 0.06, saturation: 1.04 }
};

const clamp01 = (v) => Math.min(1, Math.max(0, v));

function hexRgb(hex) {
  const v = parseInt(hex.slice(1), 16);
  return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255];
}

/** Grade one display-referred colour with a board's terms. Pure; the LUT samples it on the 17^3 lattice. */
export function gradeColor(rgb, terms) {
  const shadow = hexRgb(terms.shadow);
  const highlight = hexRgb(terms.highlight);
  const luma = 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2];
  // Weights fall to zero at the far end so pure black and the midtone grey stay close to neutral.
  const wShadow = terms.split * (1 - luma) * (1 - luma);
  const wHigh = terms.split * luma * luma;
  const out = [0, 0, 0];
  for (let c = 0; c < 3; c += 1) {
    // Tint toward the hue at constant luma: scale the tint to the pixel's luma before blending.
    const sl = 0.2126 * shadow[0] + 0.7152 * shadow[1] + 0.0722 * shadow[2] || 1;
    const hl = 0.2126 * highlight[0] + 0.7152 * highlight[1] + 0.0722 * highlight[2] || 1;
    const sTint = (shadow[c] / sl) * luma;
    const hTint = (highlight[c] / hl) * luma;
    let v = rgb[c] * (1 - wShadow - wHigh) + sTint * wShadow + hTint * wHigh;
    // Soft shoulder above 0.75: compress toward 1 without clipping.
    const knee = 0.75;
    if (v > knee) {
      const x = (v - knee) / (1 - knee);
      v = knee + (1 - knee) * (x - terms.shoulder * x * x) / (1 - terms.shoulder);
    }
    out[c] = v;
  }
  const l2 = 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2];
  return out.map((v) => clamp01(l2 + (v - l2) * terms.saturation));
}

/** The .cube text for one board (R varies fastest, as the format requires). */
export function boardLutCube(id) {
  const terms = BOARD_LUTS[id];
  if (!terms) throw new Error(`unknown board ${id}`);
  const lines = [
    `TITLE "${terms.title}"`,
    "# Generated by apps/showcase-dot-dash-3d/scripts/write-board-luts.mjs (procedural, CC0-1.0). Do not edit.",
    `LUT_3D_SIZE ${LUT_SIZE}`,
    "DOMAIN_MIN 0 0 0",
    "DOMAIN_MAX 1 1 1"
  ];
  const n = LUT_SIZE - 1;
  for (let b = 0; b < LUT_SIZE; b += 1) {
    for (let g = 0; g < LUT_SIZE; g += 1) {
      for (let r = 0; r < LUT_SIZE; r += 1) {
        const [ro, go, bo] = gradeColor([r / n, g / n, b / n], terms);
        lines.push(`${ro.toFixed(5)} ${go.toFixed(5)} ${bo.toFixed(5)}`);
      }
    }
  }
  return `${lines.join("\n")}\n`;
}

export const LUT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "public", "luts", "dot-dash-3d");

function main() {
  const check = process.argv.includes("--check");
  mkdirSync(LUT_DIR, { recursive: true });
  let drift = 0;
  for (const id of Object.keys(BOARD_LUTS)) {
    const file = path.join(LUT_DIR, `${id}.cube`);
    const text = boardLutCube(id);
    if (check) {
      let current = "";
      try { current = readFileSync(file, "utf8"); } catch { /* missing counts as drift */ }
      if (current !== text) { drift += 1; console.log(`drift ${file}`); }
    } else {
      writeFileSync(file, text);
      console.log(`wrote ${file} (${text.length} bytes)`);
    }
  }
  if (drift) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
