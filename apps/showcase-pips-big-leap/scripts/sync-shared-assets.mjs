#!/usr/bin/env node
// Writes src/aura-assets.shared.ts: the few shared-catalog entries Pip's Big Leap
// uses, copied verbatim from the repo-root src/aura-assets.ts (RH-06).
// Importing the root module pulled the whole 2.6 MB catalog into the page.
//   node apps/showcase-pips-big-leap/scripts/sync-shared-assets.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rootCatalog = resolve(appDir, "../../src/aura-assets.ts");
const outFile = resolve(appDir, "src/aura-assets.shared.ts");

export const SHARED_KEYS = [
  "auraClashCornerBrazierPylonMeshy",
  "blockfallReactorContainmentPylonMeshy",
  "fpsEnergyCorePickupMeshy",
  "galleryShiftPedestal",
  "gullsiegeBarrelMeshy",
  "gullsiegeCrateMeshy",
  "gullsiegeWatchtowerMeshy",
  "gullsiegeWindmillMeshy",
  "heatsinkArch",
  "heatsinkBoostPad",
  "heatsinkDroneNighthawk",
  "helperChar",
  "neonStreetLampProp",
  "propBoulder",
  "propConifer",
  "propRockB",
  "reactorFusionTurbineMeshy",
  "showcaseCartoonPlatformWorld",
  "showcaseKenneyVerdantPlatformerWorld",
  "showcasePlatformerBasicPack",
  "showcasePlatformerWorldLevel",
  "showcaseReadablePlatformLevel",
  "showcaseSideScrollerPlatformLevel",
  "showcaseSidekickRunner",
  "skylineCrystalShardMeshy"
];

// The world backdrops are never mounted (world.ts); certify.ts reads only their
// hash, so they are copied without their large metadata blocks.
export const HASH_ONLY_KEYS = new Set([
  "showcaseCartoonPlatformWorld",
  "showcaseKenneyVerdantPlatformerWorld",
  "showcasePlatformerBasicPack",
  "showcasePlatformerWorldLevel",
  "showcaseReadablePlatformLevel",
  "showcaseSideScrollerPlatformLevel"
]);
const HASH_ONLY_FIELDS = new Set(["type", "format", "url", "hash", "bounds", "sizeBytes"]);

const src = readFileSync(rootCatalog, "utf8");
const lines = src.split("\n");

function typeLine(key) {
  const line = lines.find((l) => l.startsWith(`  readonly "${key}": `));
  if (!line) throw new Error(`root catalog has no type entry for ${key}`);
  return line;
}

function entryBlock(key) {
  const start = lines.indexOf(`  "${key}": {`);
  if (start < 0) throw new Error(`root catalog has no entry for ${key}`);
  const end = lines.indexOf("  },", start);
  if (end < 0) throw new Error(`unterminated entry for ${key}`);
  const block = lines.slice(start, end + 1);
  if (!HASH_ONLY_KEYS.has(key)) return block.join("\n");
  const kept = [block[0]];
  let keep = false;
  for (const line of block.slice(1, -1)) {
    const field = line.match(/^    ([A-Za-z]+):/);
    if (field) keep = HASH_ONLY_FIELDS.has(field[1]);
    if (keep) kept.push(line);
  }
  kept.push(block[block.length - 1]);
  return kept.join("\n");
}

const out = [
  "// GENERATED by scripts/sync-shared-assets.mjs from the repo-root src/aura-assets.ts.",
  "// Do not edit by hand. These are the shared-catalog assets Pip's Big Leap uses;",
  "// tests/unit/pips-big-leap/shared-assets.test.ts fails when this copy drifts.",
  'import { defineAuraAssets } from "@aura3d/engine";',
  'import type { AuraAssetDefinition, AuraAssetMap } from "@aura3d/engine";',
  "",
  "type PipsSharedAssetDefinitions = {",
  ...SHARED_KEYS.map(typeLine),
  "};",
  "",
  "export const sharedAssets: AuraAssetMap<PipsSharedAssetDefinitions> = defineAuraAssets({",
  ...SHARED_KEYS.map(entryBlock),
  "} as const);",
  ""
].join("\n");

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== out) {
    console.error("src/aura-assets.shared.ts is stale: run node apps/showcase-pips-big-leap/scripts/sync-shared-assets.mjs");
    process.exit(1);
  }
  console.log("src/aura-assets.shared.ts is current");
} else {
  writeFileSync(outFile, out);
  console.log(`wrote ${outFile} (${SHARED_KEYS.length} entries, ${out.length} bytes)`);
}
