#!/usr/bin/env node
// Writes src/game/golferSkeleton.ts: the bind pose (world position + world rotation, metres) and parent of every joint of
// the Meshy golfer (public/aura-assets/links_golfer_player.*.glb), read from the GLB's own node hierarchy. swingMath/golferRetarget
// drive the Meshy rig from this table; tests/unit/aura-links-3d/golfer-retarget.test.ts re-derives it from the GLB and compares.
// Run: node apps/showcase-aura-links-3d/scripts/extract-golfer-skeleton.mjs [--check]
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = resolve(appDir, "public/aura-assets");
const glbName = readdirSync(dir).find((f) => /^links_golfer_player\.[0-9a-f]{8}\.glb$/.test(f));
const out = resolve(appDir, "src/game/golferSkeleton.ts");
export const golferGlbPath = glbName ? resolve(dir, glbName) : undefined;

export function readGlbJson(path) {
  const b = readFileSync(path);
  return JSON.parse(b.subarray(20, 20 + b.readUInt32LE(12)).toString("utf8"));
}
const qmul = (a, b) => [
  a[3] * b[0] + a[0] * b[3] + a[1] * b[2] - a[2] * b[1],
  a[3] * b[1] - a[0] * b[2] + a[1] * b[3] + a[2] * b[0],
  a[3] * b[2] + a[0] * b[1] - a[1] * b[0] + a[2] * b[3],
  a[3] * b[3] - a[0] * b[0] - a[1] * b[1] - a[2] * b[2]
];
const qrot = (q, v) => {
  const tx = 2 * (q[1] * v[2] - q[2] * v[1]), ty = 2 * (q[2] * v[0] - q[0] * v[2]), tz = 2 * (q[0] * v[1] - q[1] * v[0]);
  return [v[0] + q[3] * tx + (q[1] * tz - q[2] * ty), v[1] + q[3] * ty + (q[2] * tx - q[0] * tz), v[2] + q[3] * tz + (q[0] * ty - q[1] * tx)];
};

export function bindFromGlb(path) {
  const j = readGlbJson(path);
  const skin = j.skins[0];
  const parentOf = new Map();
  j.nodes.forEach((n, i) => (n.children ?? []).forEach((c) => parentOf.set(c, i)));
  const worldCache = new Map();
  const world = (i) => {
    if (worldCache.has(i)) return worldCache.get(i);
    const n = j.nodes[i];
    const t = n.translation ?? [0, 0, 0], r = n.rotation ?? [0, 0, 0, 1], s = n.scale ?? [1, 1, 1];
    const p = parentOf.has(i) ? world(parentOf.get(i)) : { pos: [0, 0, 0], rot: [0, 0, 0, 1], scale: 1 };
    const ts = [t[0] * p.scale, t[1] * p.scale, t[2] * p.scale];
    const wp = qrot(p.rot, ts);
    const res = { pos: [p.pos[0] + wp[0], p.pos[1] + wp[1], p.pos[2] + wp[2]], rot: qmul(p.rot, r), scale: p.scale * s[0] };
    worldCache.set(i, res);
    return res;
  };
  const joints = skin.joints.map((i) => i);
  const jointSet = new Set(joints);
  const armature = j.nodes[parentOf.get(joints.find((i) => !jointSet.has(parentOf.get(i))))];
  return joints.map((i) => {
    const w = world(i);
    const par = parentOf.get(i);
    return { name: j.nodes[i].name, parent: jointSet.has(par) ? j.nodes[par].name : null, pos: w.pos, rot: w.rot, armatureScale: armature?.scale?.[0] ?? 1 };
  });
}

const r6 = (x) => Math.round(x * 1e6) / 1e6 + 0;

export function renderTable(rows, glbName) {
  return `// Generated by apps/showcase-aura-links-3d/scripts/extract-golfer-skeleton.mjs from public/aura-assets/${glbName} - do not edit by hand.
// Bind pose of the Meshy golfer skeleton (${rows.length} joints): world position (metres, GLB space) and world rotation (x, y, z, w)
// per joint, parent joint name, in hierarchy order. The Armature node scales its children by ${rows[0].armatureScale} (cm bone units).

export interface GolferBindJoint {
  readonly name: string;
  readonly parent: string | null;
  readonly pos: readonly [number, number, number];
  readonly rot: readonly [number, number, number, number];
}

export const GOLFER_ARMATURE_SCALE = ${rows[0].armatureScale};
export const GOLFER_GLB = "${glbName}";

export const GOLFER_BIND: readonly GolferBindJoint[] = [
${rows.map((r) => `  { name: "${r.name}", parent: ${r.parent ? `"${r.parent}"` : "null"}, pos: [${r.pos.map(r6).join(", ")}], rot: [${r.rot.map(r6).join(", ")}] }`).join(",\n")}
];
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = renderTable(bindFromGlb(golferGlbPath), glbName);
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) { console.error("golferSkeleton.ts is stale"); process.exit(1); }
    console.log("golferSkeleton.ts is current");
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
