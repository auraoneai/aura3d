import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { areaOf, attribute, decodeMappings, packageOf, reportDist } from "../../../tools/bundle-report/report.mjs";

const dirs: string[] = [];
afterEach(() => { while (dirs.length) rmSync(dirs.pop()!, { recursive: true, force: true }); });

describe("bundle-report (WP-C1)", () => {
  it("decodes VLQ mappings into generated columns and cumulative source indexes", () => {
    // "AAAA" = [0,0,0,0]; "KCAA" = [5,1,0,0] (col +5, source +1); "GAAA" = [3,0,0,0]
    expect(decodeMappings("AAAA,KCAA;GAAA")).toEqual([[[0, 0], [5, 1]], [[3, 1]]]);
    expect(decodeMappings("A")).toEqual([[[0, -1]]]);
  });

  it("rolls sources up to packages and dist folders", () => {
    expect(packageOf("../node_modules/@aura3d/engine/dist/rendering/webgl2/Device.js")).toBe("@aura3d/engine");
    expect(areaOf("../node_modules/@aura3d/engine/dist/rendering/webgl2/Device.js")).toBe("@aura3d/engine > rendering/webgl2");
    expect(areaOf("../node_modules/@aura3d/engine/dist/rendering/Shader.js")).toBe("@aura3d/engine > rendering");
    expect(areaOf("../node_modules/@aura3d/engine/dist/math/Color.js")).toBe("@aura3d/engine > math");
    expect(areaOf("../node_modules/ktx-parse/dist/ktx-parse.modern.js")).toBe("ktx-parse");
    expect(areaOf("../../src/main.ts")).toBe("app");
  });

  it("attributes every generated byte exactly once", () => {
    const code = "abcdefghij\nklmno";
    const map = { sources: ["../node_modules/a/dist/x/y.js", "src/main.ts"], mappings: "AAAA,KCAA;AAAA" };
    const by = attribute(code, map);
    expect(Object.values(by).reduce((s: number, v) => s + (v as number), 0)).toBe(code.length);
    expect(by).toEqual({ app: 11, "a > x": 5 });
  });

  it("reports a dist folder with raw, gzip and per-package totals", () => {
    const dist = mkdtempSync(join(tmpdir(), "bundle-report-"));
    dirs.push(dist);
    mkdirSync(join(dist, "assets"));
    writeFileSync(join(dist, "assets", "index.js"), "abcdefghij");
    writeFileSync(join(dist, "assets", "index.js.map"), JSON.stringify({ version: 3, sources: ["../node_modules/@aura3d/engine/dist/scene/Node.js"], mappings: "AAAA" }));
    writeFileSync(join(dist, "assets", "decoder.js"), "0123456789012345");
    const r = reportDist(dist, "demo");
    expect(r).toMatchObject({ name: "demo", jsFiles: 2, totalRaw: 26 });
    expect(r.packages).toEqual({ "(no sourcemap)": 16, "@aura3d/engine": 10 });
    expect(r.areas["@aura3d/engine > scene"]).toBe(10);
    expect(r.totalGzip).toBeGreaterThan(0);
  });
});
