// ───────────────────────────── R-15: real compressed GLBs ─────────────────────────────

const FIXTURES = new URL("../../fixtures/gltf/", import.meta.url);
function fixture(name: string): ArrayBuffer {
  const bytes = readFileSync(new URL(name, FIXTURES));
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
}

/* eslint-disable @typescript-eslint/no-explicit-any */
let dracoModule: any;
async function draco(): Promise<any> {
  if (!dracoModule) {
    const draco3d = createRequire(import.meta.url)("draco3d");
    dracoModule = await draco3d.createDecoderModule();
  }
  return dracoModule;
}

/** Decode one Draco payload into per-unique-id attribute rows (shared by both loaders). */
async function decodeDraco(source: Uint8Array, uniqueIds: Readonly<Record<string, number>>) {
  const d = await draco();
  const decoder = new d.Decoder();
  const buffer = new d.DecoderBuffer();
  buffer.Init(new Int8Array(source), source.byteLength);
  const mesh = new d.Mesh();
  const status = decoder.DecodeBufferToMesh(buffer, mesh);
  if (!status.ok()) throw new Error(`draco decode failed: ${status.error_msg()}`);
  const numPoints = mesh.num_points();
  const attributes: Record<string, number[][]> = {};
  for (const [name, id] of Object.entries(uniqueIds)) {
    const attribute = decoder.GetAttributeByUniqueId(mesh, id);
    const size = attribute.num_components();
    const array = new d.DracoFloat32Array();
    decoder.GetAttributeFloatForAllPoints(mesh, attribute, array);
    const rows: number[][] = [];
    for (let i = 0; i < numPoints; i += 1) {
      const row: number[] = [];
      for (let c = 0; c < size; c += 1) row.push(array.GetValue(i * size + c));
      rows.push(row);
    }
    d.destroy(array);
    attributes[name] = rows;
  }
  const faces = mesh.num_faces();
  const indexArray = new d.DracoUInt32Array();
  const indices: number[] = [];
  for (let f = 0; f < faces; f += 1) {
    decoder.GetFaceFromMesh(mesh, f, indexArray);
    indices.push(indexArray.GetValue(0), indexArray.GetValue(1), indexArray.GetValue(2));
  }
  d.destroy(indexArray);
  d.destroy(mesh);
  d.destroy(buffer);
  d.destroy(decoder);
  return { attributes, indices };
}

/** The slice of three's DRACOLoader contract GLTFLoader uses, backed by the same draco3d wasm. */
const threeDracoShim = {
  preload() { return this; },
  decodeDracoFile(
    buffer: ArrayBuffer,
    callback: (geometry: BufferGeometry) => void,
    attributeIDs: Record<string, number>,
    _types: Record<string, string>,
    _colorSpace: unknown,
    onError?: (error: unknown) => void
  ) {
    decodeDraco(new Uint8Array(buffer), attributeIDs).then(({ attributes, indices }) => {
      const geometry = new BufferGeometry();
      geometry.setIndex(new BufferAttribute(new Uint32Array(indices), 1));
      for (const [name, rows] of Object.entries(attributes)) {
        const size = rows[0]!.length;
        geometry.setAttribute(name, new BufferAttribute(new Float32Array(rows.flat()), size));
      }
      callback(geometry);
    }, onError);
  }
};

interface PrimitiveShape {
  readonly vertices: number;
  readonly indices: number;
  readonly positions: readonly number[];
}

function threePrimitives(bytes: ArrayBuffer, configure?: (loader: ThreeGLTFLoader) => void): Promise<PrimitiveShape[]> {
  return new Promise((resolve, reject) => {
    const loader = new ThreeGLTFLoader();
    configure?.(loader);
    loader.parse(bytes.slice(0), "", (gltf) => {
      const shapes: PrimitiveShape[] = [];
      gltf.scene.traverse((node) => {
        const mesh = node as Mesh;
        if (!(mesh as { isMesh?: boolean }).isMesh) return;
        const position = mesh.geometry.attributes.position!;
        const positions: number[] = [];
        for (let i = 0; i < position.count; i += 1) positions.push(position.getX(i), position.getY(i), position.getZ(i));
        shapes.push({ vertices: position.count, indices: mesh.geometry.index?.count ?? 0, positions });
      });
      resolve(shapes);
    }, reject);
  });
}

async function auraPrimitives(bytes: ArrayBuffer, options?: ConstructorParameters<typeof GLTFLoader>[0]): Promise<PrimitiveShape[]> {
  const asset = await loadAura(bytes, options);
  return asset.meshes.map((m) => ({ vertices: m.positions.length, indices: m.indices?.length ?? 0, positions: m.positions.flat() }));
}

function expectParity(aura: PrimitiveShape[], three: PrimitiveShape[], tolerance: number) {
  expect(aura.length).toBe(2); // fixture has two primitives of different sizes
  expect(three.length).toBe(aura.length);
  // Distinct sizes so a count match cannot be a coincidence.
  expect(new Set(aura.map((p) => p.vertices)).size).toBe(aura.length);
  for (const [i, a] of aura.entries()) {
    const t = three[i]!;
    expect(a.vertices, `primitive ${i} vertex count`).toBe(t.vertices);
    expect(a.indices, `primitive ${i} index count`).toBe(t.indices);
    expect(a.vertices).toBeGreaterThan(100);
    expect(a.indices).toBeGreaterThan(300);
    let worst = 0;
    for (let k = 0; k < a.positions.length; k += 1) worst = Math.max(worst, Math.abs(a.positions[k]! - t.positions[k]!));
    expect(worst, `primitive ${i} max position delta`).toBeLessThanOrEqual(tolerance);
  }
}

function usesExtension(bytes: ArrayBuffer, name: string): boolean {
  const dv = new DataView(bytes);
  const json = JSON.parse(new TextDecoder().decode(new Uint8Array(bytes, 20, dv.getUint32(12, true)))) as { extensionsUsed?: string[] };
  return (json.extensionsUsed ?? []).includes(name);
}

describe("ST-05 real compressed GLBs vs three's GLTFLoader (R-15)", () => {
  test("Draco (KHR_draco_mesh_compression, edgebreaker): same vertex/index counts and positions", async () => {
    const bytes = fixture("draco-spheres.glb");
    expect(usesExtension(bytes, "KHR_draco_mesh_compression")).toBe(true);
    const calls: GLTFDracoDecodeDescriptor[] = [];
    const aura = await auraPrimitives(bytes, {
      dracoDecoder: async (source, descriptor) => {
        calls.push(descriptor);
        const { attributes, indices } = await decodeDraco(source, descriptor.attributes);
        return { attributes, indices };
      }
    });
    const three = await threePrimitives(bytes, (loader) => { loader.setDRACOLoader(threeDracoShim as never); });
    expect(calls).toHaveLength(2); // one real decode per primitive
    expectParity(aura, three, 1e-6);
  });

  test("Meshopt (EXT_meshopt_compression + KHR_mesh_quantization): same vertex/index counts and positions", async () => {
    const bytes = fixture("meshopt-spheres.glb");
    expect(usesExtension(bytes, "EXT_meshopt_compression")).toBe(true);
    await MeshoptDecoder.ready;
    let decoded = 0;
    const aura = await auraPrimitives(bytes, {
      meshoptDecoder: async (source, descriptor) => {
        decoded += 1;
        const out = await MeshoptDecoder.decodeGltfBufferAsync(descriptor.count, descriptor.byteStride, source, descriptor.mode, descriptor.filter);
        return out;
      }
    });
    const three = await threePrimitives(bytes, (loader) => { loader.setMeshoptDecoder(MeshoptDecoder); });
    expect(decoded).toBeGreaterThanOrEqual(6); // every compressed bufferView went through the real decoder
    // Quantized (normalized int16) positions: both loaders must dequantize to the same floats.
    expectParity(aura, three, 1e-4);
  });

  test("KTX2 (KHR_texture_basisu + real KTX2 container): geometry parity and ktx2 handling", async () => {
    const bytes = fixture("ktx2-spheres.glb");
    expect(usesExtension(bytes, "KHR_texture_basisu")).toBe(true);
    const aura = await loadAura(bytes);
    // GPU transcoding is out of reach in node (covered by the remote parity-texture spec);
    // three gets a stub KTX2Loader so its parser still walks the same texture graph.
    const ktx2Stub = { detectSupport() { return this; }, load(_url: string, onLoad: (t: Texture) => void) { onLoad(new Texture()); }, setWorkerLimit() { return this; }, dispose() {} };
    // three's image-source path reads `self.URL` (browser global).
    const g = globalThis as { self?: unknown };
    const hadSelf = "self" in g;
    if (!hadSelf) g.self = globalThis;
    let three: PrimitiveShape[];
    try {
      three = await threePrimitives(bytes, (loader) => { loader.setKTX2Loader(ktx2Stub as never); });
    } finally {
      if (!hadSelf) delete g.self;
    }
    expectParity(aura.meshes.map((m) => ({ vertices: m.positions.length, indices: m.indices?.length ?? 0, positions: m.positions.flat() })), three, 1e-6);
    expect(aura.images).toHaveLength(1);
    expect(aura.images[0]!.mimeType).toBe("image/ktx2");
    expect(aura.materials[0]!.baseColorTexture).toBeDefined();
    expect(JSON.stringify(aura.loaderDiagnostics)).toContain("ktx2");
  });
});
