/**
 * threejs-parity lane L4 ST-05: GLTF decoder plumbing parity.
 *
 * - Plain GLB geometry is compared against three r185's `GLTFLoader.parse`
 *   on the same bytes (positions/indices must match exactly).
 * - EXT_meshopt_compression routes through the injected decoder with three's
 *   `decodeGltfBufferAsync(count, stride, source, mode, filter)` contract. The
 *   descriptor contract is asserted with a capture stub; real decoding is
 *   proven on an encoded fixture in the R-15 block below.
 * - KHR_draco_mesh_compression routes through `dracoDecoder(source, desc)`
 *   where `desc` carries three's bufferView+attribute-map semantics (stub
 *   here; real draco3d decoding is in the R-15 block below).
 * - KHR_texture_basisu marks `compression:ktx2-basis` and accepts
 *   `image/ktx2` image mime types like three's GLTFLoader.
 * - R-15: three REAL compressed GLBs (tests/fixtures/gltf, regenerated by
 *   build-fixtures.mjs: Draco edgebreaker, Meshopt + quantization, KTX2
 *   container) are decoded by Aura's GLTFLoader with live Draco/Meshopt
 *   decoders and by three's GLTFLoader (same decoder wasm); per-primitive
 *   vertex counts, index counts and positions must match. KTX2 transcoding
 *   needs a GPU, so that fixture proves geometry parity + extension handling.
 */

