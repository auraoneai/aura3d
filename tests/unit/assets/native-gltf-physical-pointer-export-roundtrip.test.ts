const leaves = [
  { extension: "KHR_materials_specular", leaf: "specularFactor", values: [0.25, 0.75], interpolation: "LINEAR" },
  { extension: "KHR_materials_sheen", leaf: "sheenRoughnessFactor", values: [0.125, 0.625], interpolation: "STEP" },
  { extension: "KHR_materials_iridescence", leaf: "iridescenceFactor", values: [0.25, 0.75], interpolation: "CUBICSPLINE" },
  { extension: "KHR_materials_iridescence", leaf: "iridescenceIor", values: [1.25, 1.75], interpolation: "CUBICSPLINE" }
] as const;
type Leaf = typeof leaves[number];

function sourcePointer(leaf: Leaf): string {
  return `/materials/1/extensions/${leaf.extension}/${leaf.leaf}`;
}

function samples(leaf: Leaf): number[] {
  return leaf.interpolation === "CUBICSPLINE"
    ? [-0.125, leaf.values[0], 0.25, -0.25, leaf.values[1], 0.125]
    : [...leaf.values];
}

// Hand-authored glTF and FLOAT buffers, not generated by the exporter under test.
// Material 1 is both animated and referenced by a real triangle mesh.
function authored(leaf: Leaf, required: boolean): Record<string, any> {
  const parts = [
    new Float32Array([0, 0, 0, 1, 0, 0, 0, 1, 0]),
    new Float32Array([0, 0, 1, 0, 0, 1, 0, 0, 1]),
    new Float32Array([0, 1]),
    new Float32Array(samples(leaf)),
    new Float32Array([0, 0, 0, 2, 4, 6])
  ];
  let offset = 0;
  const bufferViews = parts.map((part) => {
    const view = { buffer: 0, byteOffset: offset, byteLength: part.byteLength };
    offset += part.byteLength;
    return view;
  });
  const bytes = Buffer.concat(parts.map((part) => Buffer.from(part.buffer, part.byteOffset, part.byteLength)));
  return {
    asset: { version: "2.0" },
    extensionsUsed: ["KHR_animation_pointer", "KHR_materials_specular", "KHR_materials_sheen", "KHR_materials_iridescence"],
    ...(required ? { extensionsRequired: ["KHR_animation_pointer"] } : {}),
    buffers: [{ uri: `data:application/octet-stream;base64,${bytes.toString("base64")}`, byteLength: bytes.length }],
    bufferViews,
    accessors: [
      { bufferView: 0, componentType: 5126, count: 3, type: "VEC3", min: [0, 0, 0], max: [1, 1, 0] },
      { bufferView: 1, componentType: 5126, count: 3, type: "VEC3" },
      { bufferView: 2, componentType: 5126, count: 2, type: "SCALAR", min: [0], max: [1] },
      { bufferView: 3, componentType: 5126, count: samples(leaf).length, type: "SCALAR" },
      { bufferView: 4, componentType: 5126, count: 2, type: "VEC3" }
    ],
    materials: [
      { name: "Other" },
      { name: "Paint.layer", extensions: {
        KHR_materials_specular: { specularFactor: 0.5 },
        KHR_materials_sheen: { sheenRoughnessFactor: 0.5 },
        KHR_materials_iridescence: { iridescenceFactor: 0.5, iridescenceIor: 1.5 }
      } },
      { name: "Third" }
    ],
    meshes: [{ name: "triangle", primitives: [{ attributes: { POSITION: 0, NORMAL: 1 }, material: 1 }] }],
    nodes: [{ name: "Model", mesh: 0 }], scenes: [{ nodes: [0] }], scene: 0,
    animations: [{
      name: "paint-and-move",
      samplers: [{ input: 2, output: 3, interpolation: leaf.interpolation }, { input: 2, output: 4, interpolation: "LINEAR" }],
      channels: [
        { sampler: 0, target: { path: "pointer", extensions: { KHR_animation_pointer: { pointer: sourcePointer(leaf) } } } },
        { sampler: 1, target: { node: 0, path: "translation" } }
      ]
    }]
  };
}

