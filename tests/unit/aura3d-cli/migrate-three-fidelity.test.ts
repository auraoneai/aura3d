import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import * as animation from "../../../packages/animation/src/index";
import { Clock } from "../../../packages/engine/src/agent-api/Clock";
import * as math from "../../../packages/math/src/index";
import { circleParityMesh } from "../../../packages/rendering/src/geometry/Circle";
import { coneParityMesh } from "../../../packages/rendering/src/geometry/Cone";
import { edgesParityMesh } from "../../../packages/rendering/src/geometry/Edges";
import { extrudeParityMesh } from "../../../packages/rendering/src/geometry/Extrude";
import { latheParityMesh } from "../../../packages/rendering/src/geometry/Lathe";
import { polyhedronParityMesh } from "../../../packages/rendering/src/geometry/Polyhedron";
import { ringParityMesh } from "../../../packages/rendering/src/geometry/Ring";
import { boxParityMesh, roundedBoxParityMesh } from "../../../packages/rendering/src/geometry/RoundedBox";
import { shapeParityMesh } from "../../../packages/rendering/src/geometry/Shape";
import { torusKnotParityMesh } from "../../../packages/rendering/src/geometry/TorusKnot";
import { tubeParityMesh } from "../../../packages/rendering/src/geometry/Tube";
import { wireframeParityMesh } from "../../../packages/rendering/src/geometry/Wireframe";
import { THREE_TO_A3D_MAPPINGS } from "../../../packages/aura3d-cli/src/migrate-three/mappings";
import { cases, TOLERANCE } from "../../fixtures/migrate-three/cases.mjs";
import { extraCases } from "../../fixtures/migrate-three/cases.extra.mjs";

// PRD beat-three.js contract 3.6: a codemod row labelled `exact` must carry a
// `test` that points at a before/after fixture. The fixture runs the same
// source against real three.js r185 (tests/fixtures/migrate-three/goldens.json,
// regenerated by generate.mjs) and against the Aura3D surface the row names;
// the outputs must agree within TOLERANCE. Rows that cannot meet that stay
// `approximate` and say why in `note`.

const repo = resolve(__dirname, "../../..");
const goldens = JSON.parse(readFileSync(resolve(repo, "tests/fixtures/migrate-three/goldens.json"), "utf8")) as {
  readonly three: string;
  readonly methods: Readonly<Record<string, readonly string[]>>;
  readonly values: Readonly<Record<string, readonly number[]>>;
};

const FIXTURE_FILE = "tests/fixtures/migrate-three/cases.mjs";
const EXTRA_FILE = "tests/fixtures/migrate-three/cases.extra.mjs";
const fixtureRef = /^(tests\/fixtures\/migrate-three\/cases(?:\.extra)?\.mjs)#([A-Za-z0-9_]+)$/;

type AuraCase = (lib: unknown) => readonly number[];
type ExtraCase = { readonly aura: (ctx: unknown) => readonly number[] };

const parity = {
  circleParityMesh, coneParityMesh, edgesParityMesh, extrudeParityMesh, latheParityMesh, polyhedronParityMesh,
  ringParityMesh, boxParityMesh, roundedBoxParityMesh, shapeParityMesh, torusKnotParityMesh, tubeParityMesh, wireframeParityMesh,
};
const auraLib = math as unknown as Record<string, unknown>;
const runAura = (name: string): readonly number[] | undefined => {
  const plain = (cases as Record<string, AuraCase>)[name];
  if (plain) return plain(auraLib);
  const extra = (extraCases as Record<string, ExtraCase>)[name];
  if (extra) return extra.aura({ animation, engine: { Clock }, math, parity });
  return undefined;
};

/**
 * Documented method gaps that do not stop a row being `exact`: the curve family has no mutating
 * `copy()` (three's Curve.copy); each such row's note says "no copy()".
 */
const CURVE_FAMILY = new Set([
  "CatmullRomCurve3", "CubicBezierCurve3", "CubicBezierCurve", "QuadraticBezierCurve3", "QuadraticBezierCurve", "LineCurve3", "LineCurve",
  "SplineCurve", "EllipseCurve", "ArcCurve", "CurvePath", "Path", "Shape",
]);

const closeTo = (a: number, b: number): boolean => Math.abs(a - b) <= TOLERANCE * Math.max(1, Math.abs(a), Math.abs(b));

/** First disagreement between the Aura run and the three.js golden, or undefined. */
const firstDivergence = (name: string): string | undefined => {
  const golden = goldens.values[name];
  if (!golden) return "no golden";
  let actual: readonly number[] | undefined;
  try {
    actual = runAura(name);
  } catch (error) {
    return `threw: ${error instanceof Error ? error.message : String(error)}`;
  }
  if (!actual) return "no case";
  if (actual.length !== golden.length) return `length ${actual.length} vs three ${golden.length}`;
  for (let i = 0; i < golden.length; i += 1) {
    if (!closeTo(actual[i]!, golden[i]!)) return `value[${i}] ${actual[i]} vs three ${golden[i]}`;
  }
  return undefined;
};

describe("migrate-three fidelity (PRD beat-three.js contract 3.6)", () => {
  it("goldens were generated from the pinned three.js", () => {
    expect(goldens.three).toBe("0.185.1");
  });

  it("every `exact` row names a fixture that exists", () => {
    const missing: string[] = [];
    for (const row of THREE_TO_A3D_MAPPINGS) {
      if (row.mapping !== "exact") continue;
      const match = row.test ? fixtureRef.exec(row.test) : null;
      if (!match) {
        missing.push(`${row.construct}: exact row has no fixture \`test\` (${String(row.test)})`);
        continue;
      }
      const [, file, name] = match;
      if (!existsSync(resolve(repo, file!))) missing.push(`${row.construct}: ${file} does not exist`);
      else if (!(name! in cases) && !(name! in extraCases)) missing.push(`${row.construct}: no case ${name}`);
      else if (name !== row.construct) missing.push(`${row.construct}: fixture case ${name} is named for a different construct`);
      else if (!goldens.values[name!]) missing.push(`${row.construct}: no three.js golden for ${name} (run generate.mjs)`);
    }
    expect(missing).toEqual([]);
  });

  it("every row that names a fixture reproduces the three.js golden within tolerance", () => {
    const failures: string[] = [];
    for (const row of THREE_TO_A3D_MAPPINGS) {
      if (!row.test) continue;
      const match = fixtureRef.exec(row.test);
      if (!match) {
        failures.push(`${row.construct}: malformed test ref ${row.test}`);
        continue;
      }
      const divergence = firstDivergence(match[2]!);
      if (divergence) failures.push(`${row.construct}: ${divergence}`);
    }
    expect(failures).toEqual([]);
  });

  it("an `exact` class row has every public three.js method (r185, goldens.json)", () => {
    const gaps: string[] = [];
    for (const row of THREE_TO_A3D_MAPPINGS) {
      if (row.mapping !== "exact") continue;
      const wanted = goldens.methods[row.construct];
      if (!wanted) continue;
      const proto = (row.construct === "Clock" ? Clock : (math as unknown as Record<string, { prototype: Record<string, unknown> }>)[row.construct])?.prototype as
        | Record<string, unknown>
        | undefined;
      const allowed = CURVE_FAMILY.has(row.construct) ? new Set(["copy"]) : new Set<string>();
      if (allowed.size > 0) expect(row.note, `${row.construct} note must disclose the missing copy()`).toContain("no copy()");
      const missing = wanted.filter((method) => !allowed.has(method) && typeof proto?.[method] !== "function");
      if (missing.length > 0) gaps.push(`${row.construct}: missing ${missing.join(", ")}`);
    }
    expect(gaps).toEqual([]);
  });

  it("no pending rows remain (M1)", () => {
    expect(THREE_TO_A3D_MAPPINGS.filter((row) => row.mapping === "pending").map((row) => row.construct)).toEqual([]);
  });

  it("fixture files exist", () => {
    expect(existsSync(resolve(repo, FIXTURE_FILE))).toBe(true);
    expect(existsSync(resolve(repo, EXTRA_FILE))).toBe(true);
  });

  it("every row carries a note", () => {
    expect(THREE_TO_A3D_MAPPINGS.filter((row) => row.note.trim() === "").map((row) => row.construct)).toEqual([]);
  });
});
