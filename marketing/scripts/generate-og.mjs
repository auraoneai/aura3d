const { chromium } = require("playwright");

async function launchChromium() {
  try {
    return await chromium.launch({ headless: true });
  } catch {
    /* fall through */
  }
  try {
    return await chromium.launch({ headless: true, channel: "chrome" });
  } catch {
    /* fall through */
  }
  const cacheDir = join(os.homedir(), "Library", "Caches", "ms-playwright");
  if (existsSync(cacheDir)) {
    const candidates = readdirSync(cacheDir)
      .filter((d) => /^chromium-\d+$/.test(d))
      .map((d) => {
        const exec = join(
          cacheDir,
          d,
          "chrome-mac",
          "Chromium.app",
          "Contents",
          "MacOS",
          "Chromium"
        );
        return existsSync(exec) ? { exec, n: Number(d.replace("chromium-", "")) } : null;
      })
      .filter(Boolean)
      .sort((a, b) => b.n - a.n);
    if (candidates.length) {
      return chromium.launch({ headless: true, executablePath: candidates[0].exec });
    }
  }
  throw new Error(
    "No Chromium available: run `npx playwright install chromium` or install Google Chrome."
  );
}

async function compressPng(buffer) {
  return sharp(buffer)
    .png({
      palette: true,
      colors: 256,
      quality: 92,
      effort: 10,
      compressionLevel: 9,
      dither: 0.9,
    })
    .toBuffer();
}

const browser = await launchChromium();
const page = await browser.newPage({ deviceScaleFactor: 1, viewport: CANVAS });
await page.setContent(HTML, { waitUntil: "load" });
await page.evaluate(() => document.fonts.ready);
await page.evaluate(async () => {
  const img = document.querySelector("img.shot");
  if (!img || !img.complete) await new Promise((r) => (img.onload = r));
  if (img) await img.decode();
});

const diagnostics = await page.evaluate(() => {
  const rect = (sel) => {
    const el = document.querySelector(sel);
    if (!el) return null;
    const r = el.getBoundingClientRect();
    return { x: +r.x.toFixed(1), y: +r.y.toFixed(1), w: +r.width.toFixed(1), h: +r.height.toFixed(1), right: +r.right.toFixed(1), bottom: +r.bottom.toFixed(1) };
  };
  const h1 = document.querySelector("h1");
  const shot = document.querySelector("img.shot");
  return {
    fonts: {
      semibold: document.fonts.check('600 46px "Graphik Web"'),
      regular: document.fonts.check('400 13px "Graphik Web"'),
      mono: document.fonts.check('400 15px "TT Commons Pro Mono"'),
    },
    h1Text: h1?.innerText.replace(/\n/g, " "),
    h1ScrollWidth: h1?.scrollWidth,
    h1ClientWidth: h1?.clientWidth,
    image: { complete: shot?.complete, naturalWidth: shot?.naturalWidth, naturalHeight: shot?.naturalHeight },
    boxes: {
      brand: rect(".brand"),
      h1: rect("h1"),
      install: rect(".install"),
      meta: rect(".meta"),
      code: rect(".code"),
      url: rect(".url"),
      browser: rect(".browser"),
      caption: rect(".caption"),
    },
  };
});

if (!diagnostics.fonts.semibold || !diagnostics.fonts.regular || !diagnostics.fonts.mono) {
  throw new Error("Brand fonts failed to load; refusing to rasterize a fallback face.");
}
// The frame is drawn at 656x369 with object-fit: cover, so it must be at least that large (the committed webp is 720x450).
if (!(diagnostics.image.naturalWidth >= 656 && diagnostics.image.naturalHeight >= 369)) {
  throw new Error(`Real screenshot failed to decode: ${JSON.stringify(diagnostics.image)}`);
}
if (diagnostics.h1ScrollWidth > diagnostics.h1ClientWidth + 1) {
  throw new Error(`Headline overflows column: ${diagnostics.h1ScrollWidth} > ${diagnostics.h1ClientWidth}`);
}
for (const [name, box] of Object.entries(diagnostics.boxes)) {
  if (box && (box.x < 0 || box.y < 0 || box.right > CANVAS.width + 0.5 || box.bottom > CANVAS.height + 0.5)) {
    throw new Error(`${name} is off-canvas: ${JSON.stringify(box)}`);
  }
}

const rawOg = await page.screenshot({ type: "png" });
// Twitter's summary_large_image card accepts 1.91:1, which 1200x630 matches.
const rawTwitter = rawOg;
await browser.close();

const outputs = [];
for (const [filename, raw] of [
  ["og-1200x630.png", rawOg],
  ["twitter-1200x630.png", rawTwitter],
]) {
  const compressed = await compressPng(raw);
  const storePath = join(OUT_STORE, filename);
  const publicPath = join(OUT_PUBLIC, filename);
  writeFileSync(storePath, compressed);
  copyFileSync(storePath, publicPath);
  const meta = await sharp(compressed).metadata();
  outputs.push({
    filename,
    storePath,
    publicPath,
    width: meta.width,
    height: meta.height,
    bytes: statSync(storePath).size,
  });
}

