/** The served `.cube` URL of a venue LUT key, or null (no LUT). */
export function venueLutUrl(key: string | null | undefined): string | null {
  if (!key || !(key in lutDefinitions)) return null;
  return slamLutAssets[key as VenueLutKey].url;
}
