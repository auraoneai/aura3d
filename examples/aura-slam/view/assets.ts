  ({
    type: "texture", format: "hdr", url: `/hdri/${id}_1k.hdr`, sizeBytes,
    metadata: { license: "CC0-1.0", provenance: { sourcePath: `public/hdri/${id}_1k.hdr`, origin: source, sha256 } }
  }) as unknown as HdriAsset;

