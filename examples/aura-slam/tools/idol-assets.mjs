#!/usr/bin/env node
// Writes examples/aura-slam/view/idolAssets.generated.ts: the admitted Aura Slam Idol GLBs (keys starting with `slam`, model type,
// source under examples/aura-slam/assets/idol) copied from the shared aura.assets.json, so the route bundles only its own
// entries instead of importing the 4.5 MB repo-wide src/aura-assets.ts.
//
//   node examples/aura-slam/tools/idol-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const manifest = JSON.parse(readFileSync(resolve(root, "aura.assets.json"), "utf8"));
const list = Array.isArray(manifest.assets) ? manifest.assets : Object.values(manifest.assets);
const mine = list
  .filter((a) => a.type === "model" && /^slam[A-Z]/.test(a.id) && String(a.source ?? "").includes("examples/aura-slam/assets/idol/"))
  .sort((a, b) => a.id.localeCompare(b.id));
const entries = mine.map((a) => `  ${a.id}: ${JSON.stringify({
  type: "model", format: "glb", url: a.url, hash: a.hash, integrity: { version: 1, digest: a.hash },
  bounds: a.bounds, sizeBytes: a.sizeBytes
})}`);
const out = resolve(here, "../view/idolAssets.generated.ts");
writeFileSync(out, `// Generated by examples/aura-slam/tools/idol-assets.mjs from aura.assets.json (tools/idol/admit.sh). Do not edit by hand.
import { defineAuraAssets, type AuraAssetDefinition, type AuraAssetMap } from "@aura3d/engine";

type IdolModelAsset = AuraAssetDefinition & { readonly type: "model"; readonly format: "glb"; readonly url: string; readonly hash: string; readonly bounds: readonly [number, number, number]; readonly sizeBytes: number };

const definitions = {
${entries.join(",\n")}
} as const;

export type IdolModelKey = keyof typeof definitions;
export const IDOL_MODEL_KEYS = Object.keys(definitions) as IdolModelKey[];
export const idolModels: AuraAssetMap<Record<IdolModelKey, IdolModelAsset>> = defineAuraAssets(definitions as never) as AuraAssetMap<Record<IdolModelKey, IdolModelAsset>>;
`);
console.log(`wrote ${out}: ${mine.map((a) => `${a.id} ${(a.sizeBytes / 1e6).toFixed(2)} MB`).join(", ")}`);
