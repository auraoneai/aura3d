#!/usr/bin/env node
// Extracts the bind skeleton of rigged Idol GLBs into examples/aura-slam/view/idolBind.generated.ts, so the athlete and umpire
// retarget (view/idolHumanoid.ts) can map the unnamed bones (bone_0..bone_N) to humanoid roles offline.
//
//   node examples/aura-slam/tools/idol-bind.mjs <key>=<path/to/key.glb> [...]
//
// Per bone: name, parent bone name, model-space bind position (metres) and rotation (x, y, z, w), with every non-bone
// ancestor (the normaliser's `auraRoot` wrapper: yaw, scale, ground offset) folded in. `rootParent` is the model-space
// transform of the top bone's parent node, which the retarget needs to turn a model-space rotation into the top bone's local one.
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../view/idolBind.generated.ts");

const qMul = (a, b) => [
  a[3] * b[0] + a[0] * b[3] + a[1] * b[2] - a[2] * b[1],
  a[3] * b[1] - a[0] * b[2] + a[1] * b[3] + a[2] * b[0],
  a[3] * b[2] + a[0] * b[1] - a[1] * b[0] + a[2] * b[3],
  a[3] * b[3] - a[0] * b[0] - a[1] * b[1] - a[2] * b[2]
];
const qRot = (q, v) => {
  const u = [q[0], q[1], q[2]];
  const s = q[3];
  const dot = u[0] * v[0] + u[1] * v[1] + u[2] * v[2];
  const cr = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
  const uu = u[0] * u[0] + u[1] * u[1] + u[2] * u[2];
  return [0, 1, 2].map((i) => 2 * dot * u[i] + (s * s - uu) * v[i] + 2 * s * cr[i]);
};
/** world transform as (t, r, s) with uniform scale (the Idol rigs and the normaliser only use uniform scale). */
const compose = (p, l) => {
  const t = qRot(p.r, l.t.map((x) => x * p.s));
  return { t: [p.t[0] + t[0], p.t[1] + t[1], p.t[2] + t[2]], r: qMul(p.r, l.r), s: p.s * l.s };
};
const local = (n) => ({ t: n.getTranslation(), r: n.getRotation(), s: n.getScale()[0] });
const round = (v, d = 6) => Math.round(v * 10 ** d) / 10 ** d;

const entries = [];
const skeletons = [];
/** the glTF JSON subset the shared humanoid driver reads (apps/showcase-port-shared/idol/humanoid.ts readIdolSkeleton) */
function skeletonJson(file) {
  const u8 = readFileSync(file);
  const len = u8.readUInt32LE(12);
  const gltf = JSON.parse(u8.subarray(20, 20 + len).toString("utf8"));
  const pick = (n) => Object.fromEntries(["name", "children", "translation", "rotation", "scale", "matrix"].filter((k) => n[k] !== undefined).map((k) => [k, n[k]]));
  return { nodes: gltf.nodes.map(pick), skins: [{ joints: gltf.skins[0].joints }] };
}
for (const arg of process.argv.slice(2)) {
  const [key, file] = arg.split("=");
  const doc = await new NodeIO().registerExtensions(ALL_EXTENSIONS).read(file);
  const skin = doc.getRoot().listSkins()[0];
  if (!skin) throw new Error(`${file}: no skin`);
  const joints = skin.listJoints();
  const jointSet = new Set(joints);
  const parentOf = new Map();
  for (const n of doc.getRoot().listNodes()) for (const c of n.listChildren()) parentOf.set(c, n);
  const worldOf = (n) => {
    const p = parentOf.get(n);
    return p ? compose(worldOf(p), local(n)) : local(n);
  };
  const bones = joints.map((j) => {
    const w = worldOf(j);
    const p = parentOf.get(j);
    return { name: j.getName(), parent: p && jointSet.has(p) ? p.getName() : null, pos: w.t.map((x) => round(x)), rot: w.r.map((x) => round(x, 7)) };
  });
  const top = joints.find((j) => !jointSet.has(parentOf.get(j)));
  const tp = parentOf.get(top);
  const rp = tp ? worldOf(tp) : { t: [0, 0, 0], r: [0, 0, 0, 1], s: 1 };
  const scale = worldOf(top).s;
  skeletons.push([key, skeletonJson(file)]);
  entries.push({ key, scale: round(scale, 8), rootParent: { pos: rp.t.map((x) => round(x)), rot: rp.r.map((x) => round(x, 7)), scale: round(rp.s, 8) }, bones });
}

const body = entries.map((e) => `  ${e.key}: ${JSON.stringify(e)}`).join(",\n");
writeFileSync(out, `// Generated by examples/aura-slam/tools/idol-bind.mjs from the rigged Idol GLBs. Do not edit by hand.\nimport type { IdolBind } from "./idolHumanoid";\nimport type { GltfJsonLike } from "../../../apps/showcase-port-shared/idol/humanoid";\n\nexport const IDOL_BINDS: Readonly<Record<string, IdolBind>> = {\n${body}\n};\n\n/** node / skin JSON of each rigged GLB for the shared humanoid driver (readIdolSkeleton) */\nexport const IDOL_SKELETON_JSON: Readonly<Record<string, GltfJsonLike>> = {\n${skeletons.map(([k, j]) => `  ${k}: ${JSON.stringify(j)}`).join(",\n")}\n};\n`);
console.log(`wrote ${out}: ${entries.map((e) => `${e.key} (${e.bones.length} bones)`).join(", ")}`);
